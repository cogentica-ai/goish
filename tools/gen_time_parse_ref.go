package time_test

import (
	"fmt"
	"testing"
	"time"
)

// Parse is layout-driven: nextStdChunk walks the layout and each
// chunk consumes its part of the value. A port that switches on a
// fixed list of layout STRINGS answers "unsupported layout" for
// everything else - including RFC3339Nano and RFC1123Z, which the
// same file declares as constants.
func TestGoishRef(t *testing.T) {
	type c struct{ lay, val string }
	cases := []c{
		{time.RFC3339, "2023-11-14T22:13:20Z"},
		{time.RFC3339, "2023-11-14T22:13:20+00:00"},
		{time.RFC3339, "2023-11-14T22:13:20-05:00"},
		{time.RFC3339, "2023-11-14T22:13:20+05:30"},
		{time.RFC3339Nano, "2023-11-14T22:13:20.123456789Z"},
		{time.RFC3339Nano, "2023-11-14T22:13:20.1Z"},
		{time.RFC3339Nano, "2023-11-14T22:13:20Z"},
		{time.RFC1123, "Tue, 14 Nov 2023 22:13:20 UTC"},
		{time.RFC1123, "Tue, 14 Nov 2023 22:13:20 GMT"},
		{time.RFC1123Z, "Tue, 14 Nov 2023 22:13:20 +0000"},
		{time.RFC1123Z, "Tue, 14 Nov 2023 22:13:20 -0800"},
		{time.RFC822, "14 Nov 23 22:13 UTC"},
		{time.RFC822Z, "14 Nov 23 22:13 +0000"},
		{time.RFC850, "Tuesday, 14-Nov-23 22:13:20 UTC"},
		{time.ANSIC, "Tue Nov 14 22:13:20 2023"},
		{time.ANSIC, "Tue Nov  4 22:13:20 2023"},
		{time.UnixDate, "Tue Nov 14 22:13:20 UTC 2023"},
		{time.RubyDate, "Tue Nov 14 22:13:20 +0000 2023"},
		{time.Kitchen, "10:13PM"},
		{time.Kitchen, "10:13AM"},
		{time.Kitchen, "12:00AM"},
		{time.Kitchen, "12:00PM"},
		{time.Stamp, "Nov 14 22:13:20"},
		{time.StampMilli, "Nov 14 22:13:20.123"},
		{time.StampMicro, "Nov 14 22:13:20.123456"},
		{time.StampNano, "Nov 14 22:13:20.123456789"},
		{time.DateTime, "2023-11-14 22:13:20"},
		{time.DateOnly, "2023-11-14"},
		{time.TimeOnly, "22:13:20"},
		{time.Layout, "11/14 10:13:20PM '23 +0000"},
		{"2006-01-02", "2023-02-29"},
		{"2006-01-02", "2024-02-29"},
		{"2006-01-02", "2023-13-01"},
		{"2006-01-02", "2023-00-01"},
		{"2006-01-02", "2023-01-32"},
		{"2006-01-02", "2023-1-1"},
		{"2006-1-2", "2023-1-1"},
		{"2006-1-2", "2023-11-14"},
		{"2006-002", "2023-001"},
		{"2006-002", "2023-365"},
		{"2006-002", "2024-060"},
		{"2006-002", "2023-366"},
		{"2006 __2", "2023  60"},
		{"06", "69"},
		{"06", "68"},
		{"06", "00"},
		{"06", "99"},
		{"15:04:05", "22:13:20"},
		{"15:04:05", "24:00:00"},
		{"15:04:05", "23:60:00"},
		{"15:04:05", "23:59:60"},
		{"15:04:05", "23:59:59.5"},
		{"15:04:05.000", "23:59:59.5"},
		{"15:04:05.000", "23:59:59.500"},
		{"15:04:05.999", "23:59:59"},
		{"15:04:05.999", "23:59:59.5"},
		{"15:04:05,000", "23:59:59,500"},
		{"3:04PM", "9:05AM"},
		{"3:04pm", "9:05am"},
		{"Jan 2 2006", "Nov 14 2023"},
		{"January 2, 2006", "November 14, 2023"},
		{"Monday", "Tuesday"},
		{"Mon", "Tue"},
		{"Mon", "Xyz"},
		{"2006-01-02T15:04:05Z0700", "2023-11-14T22:13:20Z"},
		{"2006-01-02T15:04:05Z0700", "2023-11-14T22:13:20-0500"},
		{"2006-01-02T15:04:05Z07", "2023-11-14T22:13:20-05"},
		{"2006-01-02T15:04:05Z070000", "2023-11-14T22:13:20-050000"},
		{"2006-01-02T15:04:05Z07:00:00", "2023-11-14T22:13:20-05:00:00"},
		{"2006-01-02T15:04:05-0700", "2023-11-14T22:13:20-0500"},
		{"2006-01-02T15:04:05-07:00", "2023-11-14T22:13:20-05:00"},
		{"2006-01-02T15:04:05-07", "2023-11-14T22:13:20-05"},
		{"060102150405Z0700", "231114221320Z"},
		{"20060102150405Z0700", "20231114221320Z"},
		{"20060102150405.999999999Z0700", "20231114221320.5Z"},
		{"0601021504Z0700", "2311142213Z"},
		{"2006-01-02", "2023-11-14 extra"},
		{"2006-01-02", "junk"},
		{"2006-01-02", ""},
		{"2006-01-02", "2023-11"},
		{"", ""},
		{"", "x"},
		{"MST", "UTC"},
		{"MST", "GMT"},
		{"MST", "GMT+3"},
		{"MST", "GMT-7"},
		{"MST", "CEST"},
		{"MST", "ChST"},
		{"MST", "WITA"},
		{"MST", "AB"},
		{"2006-01-02 15:04:05 -0700 MST", "2023-11-14 22:13:20 +0000 UTC"},
	}
	for i, cc := range cases {
		u, err := time.Parse(cc.lay, cc.val)
		es := ""
		if err != nil {
			es = err.Error()
		}
		fmt.Printf("p %d %q %q unix=%d nsec=%d err=%q\n",
			i, cc.lay, cc.val, u.Unix(), u.Nanosecond(), es)
	}
}
