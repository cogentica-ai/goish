#!/usr/bin/env python3
"""fiat_invert_to_rust — translate fiat/pNNN_invert.go to goish Rust.

These files are generated by github.com/mmcloughlin/addchain: a flat
sequence of Square/Mul calls and counted squaring loops implementing
exponentiation by p-2. A transposed operand or an off-by-one loop bound
produces a wrong inverse silently, so they are translated mechanically
rather than by hand. The parser raises on any statement it does not
recognise.

    scripts/fiat_invert_to_rust.py <p256_invert.go> <out.rs>
"""
import re
import sys

RE_FUNC = re.compile(r'^func \(e \*(P\d+Element)\) Invert\(x \*P\d+Element\) \*P\d+Element \{$')
RE_NEWSET = re.compile(r'^var (\w+) = new\(P\d+Element\)\.Set\((\w+)\)$')
RE_NEW = re.compile(r'^var (\w+) = new\(P\d+Element\)$')
RE_CALL = re.compile(r'^(\w+)\.(Square|Mul)\(([\w, ]+)\)$')
RE_FOR = re.compile(r'^for s := (\d+); s < (\d+); s\+\+ \{$')
RE_RET = re.compile(r'^return e\.Set\((\w+)\)$')


def operand(a):
    """Go passes *PElement everywhere; goish's Element ops take values.
    `x` is the borrowed parameter, `e` the receiver."""
    if a == 'x':
        return '*x'
    if a == 'e':
        return '*self'
    return a


def call(m, indent):
    dst, op, args = m.group(1), m.group(2), [a.strip() for a in m.group(3).split(',')]
    want = 1 if op == 'Square' else 2
    if len(args) != want:
        raise SyntaxError('%s with %d args' % (op, len(args)))
    if dst in ('x', 'e'):
        raise SyntaxError('unexpected receiver %r' % dst)
    return '%s%s.%s(%s);' % (indent, dst, op, ', '.join(operand(a) for a in args))


def main():
    src, dst = sys.argv[1], sys.argv[2]
    lines = open(src).read().split('\n')
    curve = re.search(r'(p224|p256|p384|p521)_invert', src).group(1)

    i = 0
    while not RE_FUNC.match(lines[i].strip()):
        i += 1
    elem = RE_FUNC.match(lines[i].strip()).group(1)
    go_start, i = i + 1, i + 1

    out, indent, chain = [], '    ', []
    while lines[i].strip() != '}' or indent != '    ':
        s = lines[i].strip()
        i += 1
        if not s:
            continue
        if s.startswith('//'):
            chain.append(s)                       # keep the addition chain
            continue
        if s == '}':
            indent = '    '
            out.append('    }')
            continue
        m = RE_NEWSET.match(s)
        if m:
            out.append('    let mut %s = %s::New();' % (m.group(1), elem))
            out.append('    %s.Set(%s);' % (m.group(1), operand(m.group(2))))
            continue
        m = RE_NEW.match(s)
        if m:
            out.append('    let mut %s = %s::New();' % (m.group(1), elem))
            continue
        m = RE_FOR.match(s)
        if m:
            out.append('    // Go: for s := %s; s < %s; s++' % (m.group(1), m.group(2)))
            out.append('    let mut s: int = %s;' % m.group(1))
            out.append('    while s < %s {' % m.group(2))
            indent = '        '
            continue
        m = RE_CALL.match(s)
        if m:
            out.append(call(m, indent))
            if indent != '    ':
                out.append('        s += 1;')
            continue
        m = RE_RET.match(s)
        if m:
            out.append('    return self.Set(%s);' % m.group(1))
            continue
        raise SyntaxError('unrecognised statement: %r' % s)
    go_end = i + 1

    hdr = '''// go: file crypto/internal/fips140/nistec/fiat/%(c)s_invert.go decls: %(E)s.Invert
//
// Code generated by addchain. DO NOT EDIT.
//
// Translated from Go by scripts/fiat_invert_to_rust.py. A transposed
// operand or an off-by-one loop bound here produces a wrong inverse
// silently, so the translation is mechanical and its parser raises on
// anything it does not recognise. Regenerate with scripts/fiat_gen.py.

#![allow(non_snake_case)]

use super::%(c)s::%(E)s;
use crate::types::int;

impl %(E)s {
    // go: sdk 1.25.5 crypto/internal/fips140/nistec/fiat/%(c)s_invert.go:%(s)d-%(e)d Invert
    /// Set e = 1/x, and return e.
    ///
    /// If x == 0, Invert returns e = 0.
    pub fn Invert(&mut self, x: &%(E)s) -> &mut Self {
''' % {'c': curve, 'E': elem, 's': go_start, 'e': go_end}

    body = '\n'.join('    ' + l if l.strip() else l for l in chain) + '\n'
    open(dst, 'w').write(hdr + body + '\n'.join('    ' + l for l in out) + '\n    }\n}\n')
    sys.stderr.write('%s: Invert -> %s\n' % (curve, dst))


main()
