// ─── Reflect trait ────────────────────────────────────────────────────

/// Trait implemented by every type whose `reflect.TypeOf` is supported.
/// Built-in primitives have impls in this file; user structs get them
/// from `#[goish::reflect]`.
pub trait Reflect {
    /// Returns the descriptor by value. Cheap — just a few words.
    fn __reflect_type() -> Type;

    /// Returns a deep-cloned `Value` mirror of `self`. Used by
    /// `reflect::ValueOf` and tag-driven `json.Marshal`.
    fn __reflect_value(&self) -> Value;
}

// Blanket impl: `&T: Reflect` when `T: Reflect`. Goish ports often
// pass `&val` to `reflect::ValueOf` (mirroring Go's value-style
// `reflect.ValueOf(val)` — except Go's interface{} arg auto-borrows
// where Rust's `&T` does not). The transpiler emits `ValueOf(&val)`
// uniformly; this blanket keeps the call valid whether `val` is a
// concrete `T` or already a borrow.
impl<T: Reflect + ?Sized> Reflect for &T {
    #[inline]
    fn __reflect_type() -> Type {
        T::__reflect_type()
    }
    #[inline]
    fn __reflect_value(&self) -> Value {
        (**self).__reflect_value()
    }
}

/// `reflect.TypeOf(v)` — descriptor for `v`'s static type.
pub fn TypeOf<T: Reflect + ?Sized>(_: &T) -> Type {
    T::__reflect_type()
}

/// Type-only entry point: returns the reflect descriptor for `T` without
/// requiring a value of T. Mirrors Go's `reflect.TypeOf((*T)(nil)).Elem()`
/// idiom — used to fetch the descriptor of an interface (where a real
/// value would need a concrete carrier).
pub fn TypeOfDyn<T: Reflect + ?Sized>() -> Type {
    T::__reflect_type()
}

/// `reflect.ValueOf(v)` — read-only `Value` mirror of `v`.
pub fn ValueOf<T: Reflect + ?Sized>(v: &T) -> Value {
    v.__reflect_value()
}

// ─── ValueOfAny / TypeOfAny — reflection out of `goish::Any` ─────────
//
// Go needs no such pair: `reflect.ValueOf` takes `any`, and an
// interface header always carries its dynamic type descriptor, so
// reflecting an erased value is the *only* thing reflect does.
//
// Goish has two type-erasure mechanisms with different jobs.
// `goany::Any` erases into `Arc<dyn AnyVal>` and gives downcast;
// `Reflect` gives `Value`/`Type` but is not object safe
// (`__reflect_type()` has no `self`), so a `dyn` cannot carry it.
// Until now the two did not meet, and `crypto/x509/pkix` sat at 5/6
// because `asn1.Marshal(tv.Value)` needs exactly this crossing.
//
// The crossing is made at the *wrap* site, not the read site:
// `Any::new` requires `T: Reflect` and stores both answers in the
// `AnyVal` vtable (see goany.rs). These two functions read them.
//
// The comma-ok return is the load-bearing part. `ok == false` means
// "this carrier has no reflection" — a closure, or a value wrapped
// with `Any::new_opaque`. It is NOT the same as
// `(Value::Invalid, true)`, which is the honest reflection of `nil`
// (Go's `reflect.ValueOf(nil)` is likewise the zero Value). A caller
// that will go on to marshal must be able to tell those apart: one is
// Go's "cannot marshal nil value", the other has no Go analogue at all
// and has to name the offending type. Returning `Value::Invalid` for
// both would make `asn1.Marshal` quietly emit the wrong diagnosis, and
// - through pkix's `typeName = oidString` fallback - the wrong string.

// go: none — goish idiom: Go's `reflect.ValueOf` already takes `any`.
// This is that function for goish's `Any` carrier, with the extra `ok`
// Go does not need. See the note above for why `ok` is not optional.
/// `reflect.ValueOf(x)` where `x` is a type-erased `goish::Any`.
///
/// Returns `(value, true)` when the wrapped payload was stored through
/// [`goany::Any::new`](crate::goany::Any::new) (which requires
/// `Reflect`), and `(Value::Invalid, false)` when it was stored through
/// `new_fn` / `new_opaque` and genuinely has no reflection.
pub fn ValueOfAny(v: &crate::goany::Any) -> (Value, bool) {
    return match v.0.__goish_reflect_value() {
        Some(val) => (val, true),
        None => (Value::Invalid, false),
    };
}

// go: none — goish idiom: the `Type` half of `ValueOfAny`. Go spells
// this `reflect.TypeOf(x)`; goish's `TypeOf` needs a static `T`, which
// an erased value does not have.
/// `reflect.TypeOf(x)` where `x` is a type-erased `goish::Any` — the
/// *dynamic* type descriptor, not `interface{}`.
///
/// Same `ok` contract as [`ValueOfAny`]. Note that
/// `<Any as Reflect>::__reflect_type()` cannot answer this: it has no
/// `self`, so all it can say is `interface{}`.
pub fn TypeOfAny(v: &crate::goany::Any) -> (Type, bool) {
    return match v.0.__goish_reflect_type() {
        Some(t) => (t, true),
        None => (Type::__new(Kind::Invalid, "", &[]), false),
    };
}

// ─── AnyReflect — type-erased reflection ─────────────────────────────
//
// Ports that accept arbitrary user values (logr's structured logging
// slots, json.Marshal's `any`, query.Values's interface{}, …) used to
// take `Arc<dyn core::any::Any>`. That handles concrete-type downcast
// but loses access to reflection — funcr renders unknown types as
// `"<unhandled>"`.
//
// `AnyReflect` is the supertrait that bundles both: implementers are
// `Any` (downcast-capable) AND `Reflect` (walkable via Value). The
// blanket impl below makes every `Reflect + Any + Send + Sync` type
// pick this up for free, including all `#[goish::reflect]`-tagged
// user structs and the built-in primitives.
//
// Migration path for ports: change `Arc<dyn Any + Send + Sync>` to
// `Arc<dyn AnyReflect + Send + Sync>`. Existing `downcast_ref::<T>()`
// call sites work unchanged through the `as_any()` upcast helper;
// new sites can call `.__reflect_value()` directly to get a Value.

/// Type-erased reflection handle. Combines `core::any::Any` (typeid-
/// based downcast) with goish's `Reflect` (Value walking). Use
/// `Arc<dyn AnyReflect + Send + Sync>` in port APIs that accept Go's
/// `interface{}` / `any` values.
pub trait AnyReflect: core::any::Any + Send + Sync {
    /// Upcast to `&dyn Any` so existing `Any::downcast_ref::<T>()`
    /// call sites keep working without restructuring.
    fn as_any(&self) -> &dyn core::any::Any;
    /// Walk the value into a `reflect::Value`. Same semantics as
    /// `Reflect::__reflect_value` — provided here so callers with
    /// only an `&dyn AnyReflect` reference can introspect without a
    /// concrete type.
    fn reflect_value(&self) -> Value;
    /// Return the `reflect::Type` descriptor for this value's
    /// static (concrete) type. Mirrors `Reflect::__reflect_type`.
    fn reflect_type(&self) -> Type;
}

impl<T> AnyReflect for T
where
    T: core::any::Any + Reflect + Send + Sync,
{
    fn as_any(&self) -> &dyn core::any::Any {
        self
    }
    fn reflect_value(&self) -> Value {
        <T as Reflect>::__reflect_value(self)
    }
    fn reflect_type(&self) -> Type {
        <T as Reflect>::__reflect_type()
    }
}

// go: none — goish idiom: the element/key descriptor of a composite
// `Type` is an `Option<fn() -> Type>`, and `Value::Slice` / `Value::Map`
// need a non-optional one. A descriptor that never recorded its element
// type reports `Invalid`, which is what `Type::Elem()` already does.
fn __invalidType() -> Type {
    return Type::__new(Kind::Invalid, "", &[]);
}

/// `reflect.Zero(t)` (Go 1.25 `src/reflect/value.go`) — the zero
/// `Value` for type `t`. The returned value is neither addressable nor
/// settable.
///
/// The composite kinds matter more than they look. `encoding/asn1`'s
/// `makeField` omits an `asn1:"optional"` field by testing
/// `DeepEqual(v, reflect.Zero(v.Type()))` (marshal.rs:1134), so a
/// `Kind` that answers `Invalid` here can never compare equal to a real
/// value and its optional fields are *always* emitted. That is not a
/// cosmetic difference: it put an empty element inside every
/// `AlgorithmIdentifier` whose `Parameters` Go omits, which is every
/// Ed25519 and ECDSA one, and would have made `MarshalPKIXPublicKey`
/// and every certificate built on it disagree with Go by two bytes.
///
/// Struct is derived by recursing over the descriptor's fields, so it
/// is exact for any type whose `__reflect_type` lists what
/// `__reflect_value` produces — every `#[goish::reflect]` struct, plus
/// `asn1::RawValue` and `asn1::BitString`.
///
/// **`time::Time` and `big::Int` are the deliberate exception.** Both
/// report *no* fields (Go's are unexported) while their
/// `__reflect_value` carries two synthetic ones, so a descriptor-driven
/// zero cannot match their real zero and would silently be *wrong*
/// rather than merely absent. A field-less struct descriptor therefore
/// keeps answering `Invalid` — the conservative direction, in which an
/// optional `time::Time` is emitted where Go would omit it, rather than
/// omitted where Go emits it.
pub fn Zero(t: Type) -> Value {
    match t.Kind() {
        Kind::Bool => Value::Bool(false),
        Kind::Int => Value::Int(0),
        Kind::Int8 => Value::Int8(0),
        Kind::Int16 => Value::Int16(0),
        Kind::Int32 => Value::Int32(0),
        Kind::Int64 => Value::Int(0),
        Kind::Uint => Value::Uint(0),
        Kind::Uint8 => Value::Uint8(0),
        Kind::Uint16 => Value::Uint16(0),
        Kind::Uint32 => Value::Uint32(0),
        Kind::Uint64 => Value::Uint(0),
        Kind::Uintptr => Value::Uint(0),
        Kind::Float32 => Value::Float32(0.0),
        Kind::Float64 => Value::Float64(0.0),
        Kind::String => Value::String(string::from_static("")),
        // A nil slice and an empty one are the same value in goish
        // (goslice.rs:167), so the zero slice is the empty one.
        Kind::Slice => Value::Slice {
            elem_type: t.elem.unwrap_or(__invalidType as fn() -> Type),
            items: Vec::new(),
        },
        Kind::Map => Value::Map {
            key_type: t.key.unwrap_or(__invalidType as fn() -> Type),
            value_type: t.elem.unwrap_or(__invalidType as fn() -> Type),
            entries: Vec::new(),
        },
        // Go's zero pointer is nil; `Value::Pointer(Invalid)` is the
        // encoding `IsNil` already recognises.
        Kind::Pointer => Value::Pointer(alloc::boxed::Box::new(Value::Invalid)),
        Kind::Struct => {
            // See the doc comment: a field-less descriptor is either a
            // genuinely empty struct or one hiding its state, and the
            // two are indistinguishable from here.
            let n = t.NumField();
            if n == 0 {
                return Value::Invalid;
            }
            let mut fields: Vec<Value> = Vec::with_capacity(n as usize);
            let mut i: int = 0;
            while i < n {
                fields.push(Zero((t.Field(i).Type)()));
                i += 1;
            }
            Value::Struct { ty: t, fields }
        }
        _ => Value::Invalid,
    }
}

// ─── FromReflectValue — typed setter dispatch ─────────────────────────
//
// Mirrors `json::FromValue` but over `reflect::Value`. Used by macro-
// emitted `Settable::__reflect_set_field` implementations to safely
// extract the typed payload from a Value at runtime.

pub trait FromReflectValue: Sized {
    fn from_reflect_value(v: Value) -> (Self, crate::error);
}

macro_rules! impl_from_reflect {
    ($t:ty, $variant:ident, $name:expr) => {
        impl FromReflectValue for $t {
            fn from_reflect_value(v: Value) -> (Self, crate::error) {
                match v {
                    Value::$variant(x) => (x, crate::errors::nil),
                    _ => (
                        <$t as Default>::default(),
                        crate::errors::New(concat!("reflect: expected ", $name)),
                    ),
                }
            }
        }
    };
}

impl_from_reflect!(bool, Bool, "bool");
impl_from_reflect!(int, Int, "int");
impl_from_reflect!(i8, Int8, "int8");
impl_from_reflect!(i16, Int16, "int16");
impl_from_reflect!(rune, Int32, "int32");
impl_from_reflect!(uint, Uint, "uint");
impl_from_reflect!(byte, Uint8, "uint8");
impl_from_reflect!(u16, Uint16, "uint16");
impl_from_reflect!(u32, Uint32, "uint32");
impl_from_reflect!(float32, Float32, "float32");
impl_from_reflect!(float64, Float64, "float64");
impl_from_reflect!(string, String, "string");

impl<T: FromReflectValue + Clone + Default> FromReflectValue for slice<T> {
    fn from_reflect_value(v: Value) -> (Self, crate::error) {
        match v {
            Value::Slice { items, .. } => {
                let mut out: Vec<T> = Vec::with_capacity(items.len());
                for item in items {
                    let (elem, err) = T::from_reflect_value(item);
                    if err != crate::errors::nil {
                        return (slice::__from_vec(Vec::new()), err);
                    }
                    out.push(elem);
                }
                (slice::__from_vec(out), crate::errors::nil)
            }
            _ => (
                slice::__from_vec(Vec::new()),
                crate::errors::New("reflect: expected slice"),
            ),
        }
    }
}

impl<K, V> FromReflectValue for crate::gomap::map<K, V>
where
    K: FromReflectValue + crate::gomap::GoHash + PartialEq + Default + Clone,
    V: FromReflectValue + Default + Clone,
{
    fn from_reflect_value(v: Value) -> (Self, crate::error) {
        match v {
            Value::Map { entries, .. } => {
                let mut out = crate::gomap::map::<K, V>::new();
                for (kv, vv) in entries {
                    let (k, err) = K::from_reflect_value(kv);
                    if err != crate::errors::nil {
                        return (crate::gomap::map::<K, V>::new(), err);
                    }
                    let (v, err) = V::from_reflect_value(vv);
                    if err != crate::errors::nil {
                        return (crate::gomap::map::<K, V>::new(), err);
                    }
                    out.Set(k, v);
                }
                (out, crate::errors::nil)
            }
            _ => (
                crate::gomap::map::<K, V>::new(),
                crate::errors::New("reflect: expected map"),
            ),
        }
    }
}

// ─── Mutation: SetField / SetFieldByName ──────────────────────────────
//
// Goish doesn't expose Go's `Value.Field(i).SetInt(99)` chain directly
// (that requires per-field offsets + bounded unsafe). Instead, the
// `#[goish::reflect]` macro emits a `Settable` impl per struct that
// dispatches a typed setter per field index. The free functions below
// route through that protocol — type-checked, no unsafe.
//
//   reflect::SetField(&mut p, 1, Value::Int(99))
//   reflect::SetFieldByName(&mut p, "Name", Value::String(string("a")))

/// Trait emitted by `#[goish::reflect]` for user structs. Allows
/// runtime "write field i with this Value" without unsafe.
pub trait Settable {
    /// Assigns `v` into the i-th field. Returns `nil` on success or a
    /// type-mismatch / out-of-range error.
    fn __reflect_set_field(&mut self, idx: int, v: Value) -> crate::error;
}

/// `reflect.SetField(&mut t, idx, v)` — write `v` into the i-th field.
pub fn SetField<T: Settable>(target: &mut T, idx: int, v: Value) -> crate::error {
    target.__reflect_set_field(idx, v)
}

/// `reflect.SetFieldByName(&mut t, name, v)` — look up the field by
/// declared name and write `v` into it. Returns an error if the field
/// is not found.
pub fn SetFieldByName<T: Settable + Reflect>(
    target: &mut T,
    name: &str,
    v: Value,
) -> crate::error {
    let ty = T::__reflect_type();
    for i in 0..ty.NumField() {
        if ty.Field(i).Name.as_bytes() == name.as_bytes() {
            return target.__reflect_set_field(i, v);
        }
    }
    crate::errors::New("reflect.SetFieldByName: field not found")
}

/// `reflect.Indirect(v)` — if `v` is a `Pointer`, returns the inner
/// value; otherwise returns `v` unchanged. Mirrors Go's `Indirect`.
pub fn Indirect(v: Value) -> Value {
    match v {
        Value::Pointer(_) => v.Elem(),
        _ => v,
    }
}

/// `reflect.Append(s, x...)` — append values to a `Value::Slice`.
/// Returns a new Value (goish slices are deep-cloned, so the caller
/// receives an independent copy).
pub fn Append(s: Value, items: &[Value]) -> Value {
    match s {
        Value::Slice { elem_type, items: mut existing } => {
            existing.reserve(items.len());
            for x in items {
                existing.push(x.clone());
            }
            Value::Slice { elem_type, items: existing }
        }
        _ => panic!("reflect.Append: not a slice"),
    }
}

/// `reflect.AppendSlice(s, t)` — append all of `t`'s items to `s`.
/// `t` must also be a `Value::Slice`.
pub fn AppendSlice(s: Value, t: Value) -> Value {
    let extra = match t {
        Value::Slice { items, .. } => items,
        _ => panic!("reflect.AppendSlice: src is not a slice"),
    };
    Append(s, &extra)
}

/// `reflect.VisibleFields(t)` — flat field list as `slice<StructField>`
/// (Go's `[]StructField`). In Go this walks embedded fields BFS;
/// goish v1 has no embedded fields, so this is the same as iterating
/// `Field(0..NumField())`.
pub fn VisibleFields(t: Type) -> crate::goslice::slice<StructField> {
    let n = t.NumField();
    let mut out: alloc::vec::Vec<StructField> = alloc::vec::Vec::with_capacity(n as usize);
    for i in 0..n {
        out.push(t.Field(i));
    }
    crate::goslice::slice::__from_vec(out)
}

/// `reflect.DeepEqual(x, y)` — structural equality between any two
/// reflectable values. Mirrors Go 1.25 `reflect.DeepEqual`:
///
///   * primitives compare with `==` (NaN != NaN, matching Go)
///   * slices: same length + element-wise DeepEqual
///   * maps: same length + every key has a deeply-equal value
///   * structs: same struct name + element-wise DeepEqual
///   * Invalid == Invalid
///   * different Kinds → unequal
///
/// Goish's `Value` is an acyclic deep-clone, so the visited-set
/// short-circuit Go's implementation needs (for cyclic pointer/map
/// graphs) is unnecessary here.
pub fn DeepEqual<T, U>(x: &T, y: &U) -> bool
where
    T: Reflect + ?Sized,
    U: Reflect + ?Sized,
{
    deep_value_equal(&ValueOf(x), &ValueOf(y))
}

fn deep_value_equal(a: &Value, b: &Value) -> bool {
    if a.Kind() != b.Kind() {
        return false;
    }
    match (a, b) {
        (Value::Invalid, Value::Invalid) => true,
        (Value::Bool(x), Value::Bool(y)) => x == y,
        (Value::Int(x), Value::Int(y)) => x == y,
        (Value::Int8(x), Value::Int8(y)) => x == y,
        (Value::Int16(x), Value::Int16(y)) => x == y,
        (Value::Int32(x), Value::Int32(y)) => x == y,
        (Value::Uint(x), Value::Uint(y)) => x == y,
        (Value::Uint8(x), Value::Uint8(y)) => x == y,
        (Value::Uint16(x), Value::Uint16(y)) => x == y,
        (Value::Uint32(x), Value::Uint32(y)) => x == y,
        // NaN != NaN, matching Go.
        (Value::Float32(x), Value::Float32(y)) => x == y,
        (Value::Float64(x), Value::Float64(y)) => x == y,
        (Value::String(x), Value::String(y)) => x == y,
        (Value::Slice { items: ai, .. }, Value::Slice { items: bi, .. }) => {
            if ai.len() != bi.len() {
                return false;
            }
            ai.iter()
                .zip(bi.iter())
                .all(|(x, y)| deep_value_equal(x, y))
        }
        (Value::Map { entries: ae, .. }, Value::Map { entries: be, .. }) => {
            if ae.len() != be.len() {
                return false;
            }
            // Go semantics: each key in a must map to a deeply-equal value
            // in b. Keys are sorted in our representation, but matching
            // by lookup keeps us correct even if invariants drift.
            for (ka, va) in ae {
                let mut matched = false;
                for (kb, vb) in be {
                    if deep_value_equal(ka, kb) {
                        if !deep_value_equal(va, vb) {
                            return false;
                        }
                        matched = true;
                        break;
                    }
                }
                if !matched {
                    return false;
                }
            }
            true
        }
        (
            Value::Struct { fields: af, ty: ta },
            Value::Struct { fields: bf, ty: tb },
        ) => {
            // Distinct named struct types are never deeply equal — even
            // if their field shapes coincide.
            if ta.Name() != tb.Name() {
                return false;
            }
            if af.len() != bf.len() {
                return false;
            }
            af.iter()
                .zip(bf.iter())
                .all(|(x, y)| deep_value_equal(x, y))
        }
        (Value::Pointer(pa), Value::Pointer(pb)) => deep_value_equal(pa, pb),
        _ => false,
    }
}

