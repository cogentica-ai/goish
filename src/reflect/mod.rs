// `interface{}` reflection — Go's `var x any = …` carries the dynamic
// type that reflect.ValueOf reads at runtime. Goish models `any` as
// `Arc<dyn core::any::Any + Send + Sync>`. `__reflect_type()` is
// static so it returns Kind::Interface; `__reflect_value()` runtime-
// downcasts to a known set of primitive types and falls back to
// Value::Invalid for unrecognised payloads. Equivalent to fmt::Sprintv's
// downcast table — extend the type list there and here together when
// new ports surface needs.
impl Reflect for alloc::sync::Arc<dyn core::any::Any + Send + Sync> {
    #[inline]
    fn __reflect_type() -> Type {
        Type::__new(Kind::Interface, "interface{}", &[])
    }
    fn __reflect_value(&self) -> Value {
        let any: &(dyn core::any::Any + Send + Sync) = self.as_ref();
        if let Some(v) = any.downcast_ref::<string>() {
            return Value::String(v.clone());
        }
        if let Some(v) = any.downcast_ref::<i64>() {
            return Value::Int(*v);
        }
        if let Some(v) = any.downcast_ref::<i32>() {
            return Value::Int32(*v);
        }
        if let Some(v) = any.downcast_ref::<u64>() {
            return Value::Uint(*v);
        }
        if let Some(v) = any.downcast_ref::<u32>() {
            return Value::Uint32(*v);
        }
        if let Some(v) = any.downcast_ref::<u8>() {
            return Value::Uint8(*v);
        }
        if let Some(v) = any.downcast_ref::<f64>() {
            return Value::Float64(*v);
        }
        if let Some(v) = any.downcast_ref::<f32>() {
            return Value::Float32(*v);
        }
        if let Some(v) = any.downcast_ref::<bool>() {
            return Value::Bool(*v);
        }
        // Unrecognised concrete type — fall back to Invalid (DeepEqual
        // treats Invalid==Invalid as true). Future ports needing
        // recursive struct-of-Any comparison should extend the table
        // alongside fmt::Sprintv's downcast list.
        Value::Invalid
    }
}

// `goish::Any` (interface{} newtype). This used to be a nine-entry
// `downcast_ref` probe table over the primitives, with `Value::Invalid`
// for everything else — a `pkix.Name` inside an `Any` reflected as
// "nil". It now reads the reflection the wrap site recorded, so every
// `Any::new`-constructed value reflects, not just the nine.
//
// The `Value::Invalid` fallback that remains is for the two payloads
// that really have none (`new_fn`, `new_opaque`). `Reflect` has no
// failure channel — `__reflect_value` must return *some* Value — which
// is exactly why [`ValueOfAny`] exists and why every consumer that will
// act on the result (marshal it, walk it, encode it) must go through
// that comma-ok form instead of `ValueOf`. Landing on Invalid here is
// still safe rather than silent: `asn1::makeField` rejects an invalid
// Value. It is merely less precise about *why*.
impl Reflect for crate::goany::Any {
    #[inline]
    fn __reflect_type() -> Type {
        // Static type only — `Reflect::__reflect_type` has no `self`,
        // so the dynamic answer is unreachable from here. Callers that
        // want it use `TypeOfAny`.
        Type::__new(Kind::Interface, "interface{}", &[])
    }
    fn __reflect_value(&self) -> Value {
        let (v, _ok) = ValueOfAny(self);
        return v;
    }
}

// `interface{}` reflection — AnyReflect carrier. Mirrors the
// `Arc<dyn Any + Send + Sync>` flavour above, but the supertrait
// already provides per-value Reflect dispatch, so `__reflect_value`
// just delegates. This means `reflect::ValueOf(&subject)` on a
// `&Arc<dyn AnyReflect + Send + Sync>` returns the value's actual
// Kind (Struct, Slice, Map, …) instead of collapsing to the static
// downcast table — matching Go's `reflect.ValueOf(x)` semantic
// where `x` is `interface{}` carrying a real concrete type.
impl Reflect for alloc::sync::Arc<dyn AnyReflect + Send + Sync> {
    #[inline]
    fn __reflect_type() -> Type {
        Type::__new(Kind::Interface, "interface{}", &[])
    }
    #[inline]
    fn __reflect_value(&self) -> Value {
        (**self).reflect_value()
    }
}

// ─── slice<T: Reflect> — generic Reflect impl ─────────────────────────
//
// The Type descriptor itself doesn't carry the element kind in v1
// (kept off Type to avoid generic-static issues). The element's `Type`
// is reachable via the Slice variant's `elem_type` fn pointer.

impl<T: Reflect + Clone> Reflect for slice<T> {
    fn __reflect_type() -> Type {
        Type::__new(Kind::Slice, "", &[]).__with_elem(<T as Reflect>::__reflect_type)
    }
    fn __reflect_value(&self) -> Value {
        let mut items: Vec<Value> = Vec::with_capacity(self.Len() as usize);
        for i in 0..self.Len() {
            items.push((self[i]).__reflect_value());
        }
        Value::Slice {
            elem_type: <T as Reflect>::__reflect_type,
            items,
        }
    }
}

// ─── Option<T> — Go `*T` optionality ─────────────────────────────────
//
// Goish models Go's nilable pointer fields as `Option<T>` (and the
// `nilable<T>` wrapper on top of it). Reflect maps this to
// Kind::Pointer with the established nil encoding:
// `Value::Pointer(box Value::Invalid)` (the same shape `IsNil` above
// already recognizes).

impl<T: Reflect> Reflect for Option<T> {
    fn __reflect_type() -> Type {
        Type::__new(Kind::Pointer, "", &[]).__with_elem(<T as Reflect>::__reflect_type)
    }
    fn __reflect_value(&self) -> Value {
        match self {
            Some(v) => Value::Pointer(alloc::boxed::Box::new(v.__reflect_value())),
            None => Value::Pointer(alloc::boxed::Box::new(Value::Invalid)),
        }
    }
}

impl<T: FromReflectValue> FromReflectValue for Option<T> {
    fn from_reflect_value(v: Value) -> (Self, crate::error) {
        match v {
            Value::Invalid => (None, crate::errors::nil),
            Value::Pointer(inner) => match *inner {
                Value::Invalid => (None, crate::errors::nil),
                other => {
                    let (val, err) = T::from_reflect_value(other);
                    if err != crate::errors::nil {
                        (None, err)
                    } else {
                        (Some(val), crate::errors::nil)
                    }
                }
            },
            other => {
                let (val, err) = T::from_reflect_value(other);
                if err != crate::errors::nil {
                    (None, err)
                } else {
                    (Some(val), crate::errors::nil)
                }
            }
        }
    }
}

// `nilable<T>` — same Go-*T mapping as Option<T> above (nilable is
// Option<Arc<T>>-backed; reflect sees through the Arc).

impl<T: Reflect> Reflect for crate::gonilable::nilable<T> {
    fn __reflect_type() -> Type {
        Type::__new(Kind::Pointer, "", &[]).__with_elem(<T as Reflect>::__reflect_type)
    }
    fn __reflect_value(&self) -> Value {
        if self.IsNil() {
            Value::Pointer(alloc::boxed::Box::new(Value::Invalid))
        } else {
            Value::Pointer(alloc::boxed::Box::new(self.Must().__reflect_value()))
        }
    }
}

impl<T: FromReflectValue> FromReflectValue for crate::gonilable::nilable<T> {
    fn from_reflect_value(v: Value) -> (Self, crate::error) {
        let (opt, err) = <Option<T> as FromReflectValue>::from_reflect_value(v);
        if err != crate::errors::nil {
            return (crate::gonilable::nilable::default(), err);
        }
        match opt {
            Some(val) => (crate::gonilable::nilable::new(val), crate::errors::nil),
            None => (crate::gonilable::nilable::default(), crate::errors::nil),
        }
    }
}

// ─── map<K, V: Reflect> — generic Reflect impl ────────────────────────
//
// Goish's map<K,V> is BTreeMap-backed, so __iter() walks keys in sorted
// order. We preserve that order in the Map variant, which means
// json.Marshal output is deterministic for free.

use crate::gomap::map as gomap_map;

impl<K, V> Reflect for gomap_map<K, V>
where
    K: Reflect + crate::gomap::GoHash + PartialEq + Default + Clone,
    V: Reflect + Default + Clone,
{
    fn __reflect_type() -> Type {
        Type::__new(Kind::Map, "", &[])
            .__with_key(<K as Reflect>::__reflect_type)
            .__with_elem(<V as Reflect>::__reflect_type)
    }
    fn __reflect_value(&self) -> Value {
        let mut entries: Vec<(Value, Value)> = Vec::with_capacity(self.Len() as usize);
        for (k, v) in self.__iter() {
            entries.push((k.__reflect_value(), v.__reflect_value()));
        }
        Value::Map {
            key_type: <K as Reflect>::__reflect_type,
            value_type: <V as Reflect>::__reflect_type,
            entries,
        }
    }
}
