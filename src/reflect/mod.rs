// ─── StructTag ────────────────────────────────────────────────────────

/// Mirrors `reflect.StructTag`. Holds the raw tag string verbatim
/// (e.g. `r#"json:"name" xml:"name,attr""#`) and parses on demand.
///
/// Constructors are `__new` (private path) so `#[goish::reflect]` can
/// embed it in static descriptors.
#[derive(Clone, Copy)]
pub struct StructTag {
    raw: &'static str,
}

impl StructTag {
    /// Internal constructor used by the `#[goish::reflect]` macro and
    /// by built-in Reflect impls. Empty string means "no tag".
    #[doc(hidden)]
    pub const fn __new(raw: &'static str) -> Self {
        Self { raw }
    }

    /// `Get(key)` — value for `key`, empty string if missing.
    /// Mirrors Go's `StructTag.Get`.
    ///
    /// Takes `impl AsRef<str>` so call sites can pass either a string
    /// literal (`"json"`) or a Goish `string` value — both deref to
    /// `&str` for the lookup. Goish ports often call `Tag.Get(string("json"))`
    /// because Go's source side has no `&str` distinction; widening
    /// the param is the priority #2 "Go idioms first" pattern from
    /// CLAUDE.md.
    pub fn Get<S: AsRef<str>>(&self, key: S) -> string {
        let (v, _) = self.Lookup(key);
        v
    }

    /// `Lookup(key)` — `(value, ok)`. `ok` distinguishes "absent" from
    /// "present with empty value". Verbatim port of Go 1.25
    /// `reflect.StructTag.Lookup` (reflect/type.go:1056). Same widened
    /// param as `Get`.
    pub fn Lookup<S: AsRef<str>>(&self, key: S) -> (string, bool) {
        let key_bytes = key.as_ref().as_bytes();
        let mut tag = self.raw.as_bytes();

        while !tag.is_empty() {
            // Skip leading space.
            let mut i = 0;
            while i < tag.len() && tag[i] == b' ' {
                i += 1;
            }
            tag = &tag[i..];
            if tag.is_empty() {
                break;
            }

            // Scan to colon. A space, quote, or control char is a syntax error.
            i = 0;
            while i < tag.len()
                && tag[i] > b' '
                && tag[i] != b':'
                && tag[i] != b'"'
                && tag[i] != 0x7f
            {
                i += 1;
            }
            if i == 0 || i + 1 >= tag.len() || tag[i] != b':' || tag[i + 1] != b'"' {
                break;
            }
            let name = &tag[..i];
            tag = &tag[i + 1..];

            // Scan quoted string.
            i = 1;
            while i < tag.len() && tag[i] != b'"' {
                if tag[i] == b'\\' {
                    i += 1;
                }
                i += 1;
            }
            if i >= tag.len() {
                break;
            }
            let qvalue = &tag[..i + 1];
            tag = &tag[i + 1..];

            if key_bytes == name {
                if let Some(v) = unquote_tag_value(qvalue) {
                    return (v, true);
                }
                break;
            }
        }
        (string::new(), false)
    }
}

/// Strip surrounding `"` and apply Go string-literal escape rules to the
/// inside. Returns `None` on malformed input (mirrors strconv.Unquote err).
fn unquote_tag_value(q: &[u8]) -> Option<string> {
    if q.len() < 2 || q[0] != b'"' || q[q.len() - 1] != b'"' {
        return None;
    }
    let inner = &q[1..q.len() - 1];
    let mut out: alloc::vec::Vec<u8> = alloc::vec::Vec::with_capacity(inner.len());
    let mut i = 0;
    while i < inner.len() {
        let c = inner[i];
        if c != b'\\' {
            out.push(c);
            i += 1;
            continue;
        }
        // escape sequence
        i += 1;
        if i >= inner.len() {
            return None;
        }
        match inner[i] {
            b'"' => out.push(b'"'),
            b'\\' => out.push(b'\\'),
            b'/' => out.push(b'/'),
            b'n' => out.push(b'\n'),
            b'r' => out.push(b'\r'),
            b't' => out.push(b'\t'),
            b'a' => out.push(0x07),
            b'b' => out.push(0x08),
            b'f' => out.push(0x0C),
            b'v' => out.push(0x0B),
            b'0' => out.push(0),
            b'\'' => out.push(b'\''),
            // \xNN / \uNNNN are not parsed in v1 — tag values almost
            // never use them in practice. Add when needed.
            _ => return None,
        }
        i += 1;
    }
    Some(string::__from_vec(out))
}

// ─── StructField ──────────────────────────────────────────────────────

/// Mirrors `reflect.StructField`. Held by value inside a `Type`'s field
/// table. `Type` is a fn pointer for late binding (breaks recursion when
/// a struct field type is itself a Reflect type that hasn't been defined
/// when the descriptor is built).
#[derive(Clone, Copy)]
pub struct StructField {
    pub Name: &'static str,
    pub Tag: StructTag,
    pub Type: fn() -> Type,
    /// Mirrors `reflect.StructField.PkgPath` — non-empty marks the
    /// field unexported. Goish currently exposes only exported fields
    /// via `#[goish::reflect]`, so this is always `""`. Present so
    /// ports that test `f.PkgPath != ""` skip-unexported branches
    /// compile and behave as no-ops.
    pub PkgPath: &'static str,
    /// Mirrors `reflect.StructField.Anonymous` — true for embedded
    /// (no-name) fields. Goish's reflect descriptor doesn't yet model
    /// embedding, so this is always `false`. Present so ports that
    /// branch on `f.Anonymous` for embedded-walk compile.
    pub Anonymous: bool,
}

// ─── Type ─────────────────────────────────────────────────────────────

/// Mirrors `reflect.Type`. The struct is value-typed; `TypeOf` returns
/// it by value (cheap — a few words). `elem` and `key` carry late-bound
/// element/key descriptors for Slice / Map / Pointer kinds.
///
/// Eq/Ord/Hash compare by `(kind, name)` — same identity Go uses for
/// `reflect.Type` (each named type is unique, and Type is comparable).
/// This lets `map<reflect::Type, V>` and `map[reflect::Type] = ...` work
/// in Go ports that key caches on type.
#[derive(Clone, Copy)]
pub struct Type {
    kind: Kind,
    name: &'static str,
    fields: &'static [StructField],
    elem: Option<fn() -> Type>,
    key: Option<fn() -> Type>,
}

impl PartialEq for Type {
    fn eq(&self, other: &Self) -> bool {
        self.kind == other.kind && self.name == other.name
    }
}
impl Eq for Type {}
impl PartialOrd for Type {
    fn partial_cmp(&self, other: &Self) -> Option<core::cmp::Ordering> {
        Some(self.cmp(other))
    }
}
impl Ord for Type {
    fn cmp(&self, other: &Self) -> core::cmp::Ordering {
        (self.kind as u8, self.name).cmp(&(other.kind as u8, other.name))
    }
}
impl core::hash::Hash for Type {
    fn hash<H: core::hash::Hasher>(&self, state: &mut H) {
        (self.kind as u8).hash(state);
        self.name.hash(state);
    }
}

impl crate::gomap::GoHash for Type {
    fn go_hash(&self, seed: u64) -> u64 {
        crate::gomap::hash_bytes(self.name.as_bytes(), seed)
    }
}

impl Type {
    /// Internal constructor for `#[goish::reflect]` and built-in impls.
    #[doc(hidden)]
    pub const fn __new(
        kind: Kind,
        name: &'static str,
        fields: &'static [StructField],
    ) -> Self {
        Self {
            kind,
            name,
            fields,
            elem: None,
            key: None,
        }
    }

    /// Builder hook for slice/pointer/map element types.
    #[doc(hidden)]
    pub const fn __with_elem(self, e: fn() -> Type) -> Self {
        Self { elem: Some(e), ..self }
    }

    /// Builder hook for map key types.
    #[doc(hidden)]
    pub const fn __with_key(self, k: fn() -> Type) -> Self {
        Self { key: Some(k), ..self }
    }

    /// `Name()` — declared type name as goish `string`, or empty
    /// string for unnamed types. (Internal: the underlying field is
    /// `&'static str` since the name comes from the
    /// `#[goish::reflect]` proc-macro at compile time; we wrap it
    /// in a `string` at the API boundary.)
    pub fn Name(&self) -> crate::gostring::string {
        crate::gostring::string::from_static(self.name)
    }

    /// `Kind()` — kind tag.
    pub fn Kind(&self) -> Kind {
        self.kind
    }

    /// `NumField()` — number of struct fields. Panics in Go for non-struct
    /// kinds; here we return 0 (less surprising for boilerplate code).
    pub fn NumField(&self) -> int {
        self.fields.len() as int
    }

    /// `Field(i)` — i-th struct field. Panics if out of range.
    pub fn Field(&self, i: int) -> StructField {
        if i < 0 || (i as usize) >= self.fields.len() {
            panic!("reflect: Field index out of bounds");
        }
        self.fields[i as usize]
    }

    /// `FieldByName(name)` — `(field, ok)`. Linear scan.
    ///
    /// Takes `name: &str` for the same literal-friendliness reason as
    /// `StructTag::Get`.
    pub fn FieldByName(&self, name: &str) -> (StructField, bool) {
        for f in self.fields {
            if f.Name.as_bytes() == name.as_bytes() {
                return (*f, true);
            }
        }
        (
            StructField {
                Name: "",
                Tag: StructTag::__new(""),
                Type: || Type::__new(Kind::Invalid, "", &[]),
                PkgPath: "",
                Anonymous: false,
            },
            false,
        )
    }

    /// `Elem()` — element type for Slice / Map / Pointer. Panics for
    /// other kinds, mirroring Go.
    pub fn Elem(&self) -> Type {
        match self.elem {
            Some(f) => f(),
            None => panic!("reflect: Elem of type that has no element"),
        }
    }

    /// `Key()` — key type for Map. Panics for other kinds.
    pub fn Key(&self) -> Type {
        match self.key {
            Some(f) => f(),
            None => panic!("reflect: Key of non-map type"),
        }
    }

    /// `Comparable()` — Go semantics. Primitives + Pointer + (Struct of
    /// comparables) are comparable; Slice and Map are not.
    pub fn Comparable(&self) -> bool {
        match self.kind {
            Kind::Bool
            | Kind::Int
            | Kind::Int8
            | Kind::Int16
            | Kind::Int32
            | Kind::Uint
            | Kind::Uint8
            | Kind::Uint16
            | Kind::Uint32
            | Kind::Float32
            | Kind::Float64
            | Kind::String
            | Kind::Pointer => true,
            Kind::Slice | Kind::Map => false,
            Kind::Struct => self.fields.iter().all(|f| (f.Type)().Comparable()),
            // Interface comparability depends on the dynamic type — Go
            // returns true (the comparison may panic at runtime if the
            // dynamic type is non-comparable). v1 follows Go.
            Kind::Interface => true,
            Kind::Int64 | Kind::Uint64 | Kind::Uintptr => true,
            Kind::Func | Kind::Chan | Kind::UnsafePointer => false,
            Kind::Array => self.fields.iter().all(|f| (f.Type)().Comparable()),
            // Complex types are comparable in Go (==/!= use IEEE-754 rules).
            // Goish v1 has no native complex arithmetic; this arm exists for
            // parity so reflect-driven match-on-Kind compiles.
            Kind::Complex64 | Kind::Complex128 => true,
            Kind::Invalid => false,
        }
    }

    /// `AssignableTo(u)` — v1 simplification: Kind must match; for named
    /// types Name must match; for slice/map element & key types must be
    /// recursively assignable. (Go's full interface-satisfaction logic
    /// is out of scope until goish gains an interface type.)
    pub fn AssignableTo(&self, u: &Type) -> bool {
        if self.kind != u.kind {
            return false;
        }
        if !self.name.is_empty() || !u.name.is_empty() {
            return self.name == u.name;
        }
        match self.kind {
            Kind::Slice => {
                if self.elem.is_none() || u.elem.is_none() {
                    return false;
                }
                self.Elem().AssignableTo(&u.Elem())
            }
            Kind::Map => {
                if self.elem.is_none() || u.elem.is_none() || self.key.is_none() || u.key.is_none() {
                    return false;
                }
                self.Key().AssignableTo(&u.Key()) && self.Elem().AssignableTo(&u.Elem())
            }
            _ => true,
        }
    }

    /// `FieldByIndex(index)` — nested field by index path. Mirrors
    /// Go's `Type.FieldByIndex`. Panics on out-of-range.
    pub fn FieldByIndex(&self, index: &[int]) -> StructField {
        let mut t = *self;
        let mut f: Option<StructField> = None;
        for (i, &x) in index.iter().enumerate() {
            if i > 0 {
                t = match f {
                    Some(ff) => (ff.Type)(),
                    None => t,
                };
            }
            f = Some(t.Field(x));
        }
        f.expect("reflect: FieldByIndex with empty index")
    }

    /// `FieldByIndexErr(index)` — `(field, error)` form. In goish this
    /// is equivalent to `FieldByIndex` (we don't traverse pointers, so
    /// the "indirection through nil" error case Go raises doesn't
    /// arise). Provided for API parity.
    pub fn FieldByIndexErr(&self, index: &[int]) -> (StructField, crate::error) {
        (self.FieldByIndex(index), crate::errors::nil)
    }

    /// `FieldByNameFunc(match)` — find first field whose name satisfies
    /// `match`. Returns `(field, ok)`.
    pub fn FieldByNameFunc<F: Fn(&str) -> bool>(&self, m: F) -> (StructField, bool) {
        for f in self.fields {
            if m(f.Name) {
                return (*f, true);
            }
        }
        (
            StructField {
                Name: "",
                Tag: StructTag::__new(""),
                Type: || Type::__new(Kind::Invalid, "", &[]),
                PkgPath: "",
                Anonymous: false,
            },
            false,
        )
    }

    /// `OverflowInt(x)` — true if `x` is out of range for this signed-int
    /// type. Panics for non-int kinds.
    pub fn OverflowInt(&self, x: int) -> bool {
        let bit_size = match self.kind {
            Kind::Int => 64,
            Kind::Int8 => 8,
            Kind::Int16 => 16,
            Kind::Int32 => 32,
            _ => panic!("reflect.Type.OverflowInt of non-int"),
        };
        if bit_size == 64 {
            return false;
        }
        let shift = 64 - bit_size;
        let trunc = (x << shift) >> shift;
        x != trunc
    }

    /// `OverflowUint(x)` — true if `x` is out of range for this
    /// unsigned-int type.
    pub fn OverflowUint(&self, x: uint) -> bool {
        let bit_size = match self.kind {
            Kind::Uint => 64,
            Kind::Uint8 => 8,
            Kind::Uint16 => 16,
            Kind::Uint32 => 32,
            _ => panic!("reflect.Type.OverflowUint of non-uint"),
        };
        if bit_size == 64 {
            return false;
        }
        let shift = 64 - bit_size;
        let trunc = (x << shift) >> shift;
        x != trunc
    }

    /// `OverflowFloat(x)` — true if `x` cannot be represented in this
    /// float type without losing magnitude.
    pub fn OverflowFloat(&self, x: float64) -> bool {
        match self.kind {
            Kind::Float64 => false,
            Kind::Float32 => {
                let ax = if x < 0.0 { -x } else { x };
                ax > float32::MAX as float64
            }
            _ => panic!("reflect.Type.OverflowFloat of non-float"),
        }
    }

    /// `String()` — readable type name. `[]int`, `map[string]int`,
    /// `*Person`, `Person`, `int`, etc. Mirrors Go's `Type.String()`.
    pub fn String(&self) -> string {
        match self.kind {
            Kind::Slice => {
                let mut out: alloc::vec::Vec<u8> = b"[]".to_vec();
                if let Some(e) = self.elem {
                    out.extend_from_slice(e().String().as_bytes());
                }
                string::__from_vec(out)
            }
            Kind::Map => {
                let mut out: alloc::vec::Vec<u8> = b"map[".to_vec();
                if let Some(k) = self.key {
                    out.extend_from_slice(k().String().as_bytes());
                }
                out.push(b']');
                if let Some(e) = self.elem {
                    out.extend_from_slice(e().String().as_bytes());
                }
                string::__from_vec(out)
            }
            Kind::Pointer => {
                let mut out: alloc::vec::Vec<u8> = b"*".to_vec();
                if let Some(e) = self.elem {
                    out.extend_from_slice(e().String().as_bytes());
                }
                string::__from_vec(out)
            }
            _ => {
                if self.name.is_empty() {
                    self.kind.String()
                } else {
                    string::from_static(self.name)
                }
            }
        }
    }
}

// ─── Value ────────────────────────────────────────────────────────────
//
// Read-only value introspection. Unlike Go's `reflect.Value` (fat
// pointer over the original storage), goish's `Value` is a deep-cloned
// enum — every `ValueOf(&x)` walks `x` once and copies its data into
// the variant. Trade: copies on construction; gain: no unsafe pointer
// arithmetic, no offset_of needed, lifetime-free at the user surface.
//
// Mutation (`SetBool`, `SetString`, etc.) requires the pointer-form and
// is deferred to a later iteration.

/// Mirrors `reflect.Value` (read-only).
///
/// `Default` returns `Value::Invalid` — matches Go's zero-`reflect.Value`,
/// where `IsValid()` is false. Ports that hold a `reflect::Value` field
/// (e.g. kylelemons' `formatter.cur`) rely on this to derive `Default`.
#[derive(Clone, Default, PartialEq)]
pub enum Value {
    #[default]
    Invalid,
    Bool(bool),
    Int(int),
    Int8(i8),
    Int16(i16),
    Int32(i32), // covers rune
    Uint(uint),
    Uint8(u8), // covers byte
    Uint16(u16),
    Uint32(u32),
    Float32(float32),
    Float64(float64),
    String(string),
    Slice {
        elem_type: fn() -> Type,
        items: Vec<Value>,
    },
    Map {
        key_type: fn() -> Type,
        value_type: fn() -> Type,
        /// (key, value) pairs in stable order. Goish's `map<K,V>` is
        /// BTreeMap-backed, so this list is key-sorted; that's also the
        /// order we use for json.Marshal output.
        entries: Vec<(Value, Value)>,
    },
    Struct {
        ty: Type,
        fields: Vec<Value>,
    },
    Pointer(Box<Value>),
    /// A *named* type whose underlying kind is not a struct — Go's
    /// `type ObjectIdentifier []int`, `type Enumerated int`.
    ///
    /// Every other variant reconstructs its `Type` from the variant tag
    /// alone, which is right for `int` and `[]int` and wrong the moment a
    /// port declares a name over one: the name is what distinguishes
    /// `asn1.ObjectIdentifier` from any other `[]int`, and losing it made
    /// `encoding/asn1`'s makeBody encode an OID as a SEQUENCE OF INTEGER.
    /// Struct-shaped named types were already fine — `Struct` carries its
    /// `ty` — so this covers the rest.
    ///
    /// Everything but `Type()` delegates to `inner`, so a `Named` behaves
    /// exactly like the value it wraps.
    Named {
        ty: Type,
        inner: Box<Value>,
    },
}

impl Value {
    /// `Kind()` — runtime tag.
    pub fn Kind(&self) -> Kind {
        match self {
            Value::Named { inner, .. } => inner.Kind(),
            Value::Invalid => Kind::Invalid,
            Value::Bool(_) => Kind::Bool,
            Value::Int(_) => Kind::Int,
            Value::Int8(_) => Kind::Int8,
            Value::Int16(_) => Kind::Int16,
            Value::Int32(_) => Kind::Int32,
            Value::Uint(_) => Kind::Uint,
            Value::Uint8(_) => Kind::Uint8,
            Value::Uint16(_) => Kind::Uint16,
            Value::Uint32(_) => Kind::Uint32,
            Value::Float32(_) => Kind::Float32,
            Value::Float64(_) => Kind::Float64,
            Value::String(_) => Kind::String,
            Value::Slice { .. } => Kind::Slice,
            Value::Map { .. } => Kind::Map,
            Value::Struct { .. } => Kind::Struct,
            Value::Pointer(_) => Kind::Pointer,
        }
    }

    /// `Type()` — descriptor of this value's type.
    pub fn Type(&self) -> Type {
        match self {
            // The whole point of the variant: a named type keeps its name.
            Value::Named { ty, .. } => *ty,
            Value::Struct { ty, .. } => *ty,
            Value::Slice { elem_type, .. } => {
                Type::__new(Kind::Slice, "", &[]).__with_elem(*elem_type)
            }
            Value::Map { key_type, value_type, .. } => Type::__new(Kind::Map, "", &[])
                .__with_key(*key_type)
                .__with_elem(*value_type),
            _ => Type::__new(self.Kind(), self.Kind().__static_name(), &[]),
        }
    }

    /// `IsValid()` — false for the zero-Value (`Value::Invalid`).
    pub fn IsValid(&self) -> bool {
        if let Value::Named { inner, .. } = self {
            return inner.IsValid();
        }
        !matches!(self, Value::Invalid)
    }

    /// `IsZero()` — true if the value is its type's zero value. Mirrors
    /// Go's `reflect.Value.IsZero`.
    pub fn IsZero(&self) -> bool {
        match self {
            Value::Named { inner, .. } => inner.IsZero(),
            Value::Invalid => true,
            Value::Bool(b) => !*b,
            Value::Int(n) => *n == 0,
            Value::Int8(n) => *n == 0,
            Value::Int16(n) => *n == 0,
            Value::Int32(n) => *n == 0,
            Value::Uint(n) => *n == 0,
            Value::Uint8(n) => *n == 0,
            Value::Uint16(n) => *n == 0,
            Value::Uint32(n) => *n == 0,
            Value::Float32(f) => *f == 0.0,
            Value::Float64(f) => *f == 0.0,
            Value::String(s) => s.as_bytes().is_empty(),
            Value::Slice { items, .. } => items.is_empty(),
            Value::Map { entries, .. } => entries.is_empty(),
            Value::Struct { fields, .. } => fields.iter().all(Value::IsZero),
            Value::Pointer(_) => false,
        }
    }

    /// `Bool()` — panics if Kind != Bool.
    pub fn Bool(&self) -> bool {
        if let Value::Named { inner, .. } = self {
            return inner.Bool();
        }
        match self {
            Value::Bool(b) => *b,
            _ => panic!("reflect.Value.Bool of non-bool"),
        }
    }

    /// `Int()` — typed accessor for any signed-int kind. Panics otherwise.
    pub fn Int(&self) -> int {
        if let Value::Named { inner, .. } = self {
            return inner.Int();
        }
        match self {
            Value::Int(n) => *n,
            Value::Int8(n) => *n as int,
            Value::Int16(n) => *n as int,
            Value::Int32(n) => *n as int,
            _ => panic!("reflect.Value.Int of non-int"),
        }
    }

    /// `Uint()` — any unsigned-int kind. Panics otherwise.
    pub fn Uint(&self) -> uint {
        if let Value::Named { inner, .. } = self {
            return inner.Uint();
        }
        match self {
            Value::Uint(n) => *n,
            Value::Uint8(n) => *n as uint,
            Value::Uint16(n) => *n as uint,
            Value::Uint32(n) => *n as uint,
            _ => panic!("reflect.Value.Uint of non-uint"),
        }
    }

    /// `Float()` — float32 or float64. Panics otherwise.
    pub fn Float(&self) -> float64 {
        if let Value::Named { inner, .. } = self {
            return inner.Float();
        }
        match self {
            Value::Float32(f) => *f as float64,
            Value::Float64(f) => *f,
            _ => panic!("reflect.Value.Float of non-float"),
        }
    }

    /// `String()` — string value, or kind label for non-strings (matches
    /// Go: `reflect.Value.String` returns `"<int Value>"` for non-string).
    pub fn String(&self) -> string {
        match self {
            Value::String(s) => s.clone(),
            _ => self.Kind().String(),
        }
    }

    /// `Len()` — element count for slice/string/map. Panics otherwise.
    pub fn Len(&self) -> int {
        if let Value::Named { inner, .. } = self {
            return inner.Len();
        }
        match self {
            Value::Slice { items, .. } => items.len() as int,
            Value::String(s) => s.as_bytes().len() as int,
            Value::Map { entries, .. } => entries.len() as int,
            _ => panic!("reflect.Value.Len of non-slice/string/map"),
        }
    }

    /// `Cap()` — capacity for slice. Goish slices are deep-cloned and
    /// don't track capacity separately from length, so `Cap == Len`.
    /// Panics for non-slice (matches Go for non-Array/Chan/Slice).
    pub fn Cap(&self) -> int {
        if let Value::Named { inner, .. } = self {
            return inner.Cap();
        }
        match self {
            Value::Slice { items, .. } => items.len() as int,
            _ => panic!("reflect.Value.Cap of non-slice"),
        }
    }

    /// `IsNil()` — Go semantics for nil-able kinds:
    ///   * Pointer: inner is `Value::Invalid`
    ///   * Slice / Map: always `false` in goish v1 (we don't track nil
    ///     vs empty distinctly; an empty slice is non-nil-empty)
    ///   * Other kinds: panic
    pub fn IsNil(&self) -> bool {
        if let Value::Named { inner, .. } = self {
            return inner.IsNil();
        }
        match self {
            Value::Slice { .. } => false,
            Value::Map { .. } => false,
            Value::Pointer(inner) => matches!(**inner, Value::Invalid),
            // Func / Chan / Interface / UnsafePointer don't have a
            // primitive variant in goish v1; reflect-driven IsNil
            // checks (e.g. typeutils.IsNil) just return false here.
            // Real callers wanting nil-detection on these should use
            // the typed `== nil` comparison instead.
            Value::Invalid => true,
            _ => false,
        }
    }

    /// `reflect.Value.Interface()` (Go 1.25 `src/reflect/value.go`) —
    /// extracts the underlying value as `interface{}`. Goish models
    /// `interface{}` as `Arc<dyn Any + Send + Sync>`. Round-trips
    /// through known Value variants; `Invalid` and unsupported variants
    /// box `()` as a placeholder so call sites still get something.
    pub fn Interface(&self) -> alloc::sync::Arc<dyn core::any::Any + Send + Sync> {
        if let Value::Named { inner, .. } = self {
            return inner.Interface();
        }
        match self {
            Value::Bool(b) => alloc::sync::Arc::new(*b),
            Value::Int(n) => alloc::sync::Arc::new(*n),
            Value::Int8(n) => alloc::sync::Arc::new(*n),
            Value::Int16(n) => alloc::sync::Arc::new(*n),
            Value::Int32(n) => alloc::sync::Arc::new(*n),
            Value::Uint(n) => alloc::sync::Arc::new(*n),
            Value::Uint8(n) => alloc::sync::Arc::new(*n),
            Value::Uint16(n) => alloc::sync::Arc::new(*n),
            Value::Uint32(n) => alloc::sync::Arc::new(*n),
            Value::Float32(f) => alloc::sync::Arc::new(*f),
            Value::Float64(f) => alloc::sync::Arc::new(*f),
            Value::String(s) => alloc::sync::Arc::new(s.clone()),
            // Slice/Map/Struct/Pointer/Invalid: box `()` as placeholder.
            // A future port that needs typed re-extraction can extend
            // each variant with the original payload via `Arc<dyn Any>`
            // stored alongside.
            _ => alloc::sync::Arc::new(()),
        }
    }

    /// `Bytes()` — convert a `Value::Slice` whose element kind is
    /// `Uint8` into a `slice<byte>`. Panics otherwise.
    pub fn Bytes(&self) -> slice<byte> {
        if let Value::Named { inner, .. } = self {
            return inner.Bytes();
        }
        match self {
            Value::Slice { items, elem_type } if elem_type().Kind() == Kind::Uint8 => {
                let mut out: Vec<byte> = Vec::with_capacity(items.len());
                for item in items {
                    out.push(match item {
                        Value::Uint8(b) => *b,
                        _ => 0,
                    });
                }
                slice::__from_vec(out)
            }
            _ => panic!("reflect.Value.Bytes of non-byte slice"),
        }
    }

    /// `Slice(low, high)` — sub-slice via reflect. Mirrors Go's
    /// `Value.Slice` for slice/string. Panics for other kinds.
    pub fn Slice(&self, low: int, high: int) -> Value {
        match self {
            Value::Slice { elem_type, items } => {
                let lo = low as usize;
                let hi = high as usize;
                let sub = items[lo..hi].to_vec();
                Value::Slice {
                    elem_type: *elem_type,
                    items: sub,
                }
            }
            Value::String(s) => {
                let bytes = s.as_bytes();
                let lo = low as usize;
                let hi = high as usize;
                Value::String(string::from_bytes(&bytes[lo..hi]))
            }
            _ => panic!("reflect.Value.Slice of non-slice/string"),
        }
    }

    /// `Slice3(low, high, max)` — explicit-cap variant. Goish slices are
    /// deep-cloned, so the cap argument is ignored; semantically
    /// identical to `Slice(low, high)`.
    pub fn Slice3(&self, low: int, high: int, _max: int) -> Value {
        self.Slice(low, high)
    }

    /// `Elem()` — for Pointer: the inner Value. For other kinds, panics
    /// (matches Go's reflect.Value.Elem semantics for the cases goish
    /// supports — Interface kind is out-of-scope).
    pub fn Elem(&self) -> Value {
        match self {
            Value::Pointer(inner) => (**inner).clone(),
            _ => panic!("reflect.Value.Elem: not a pointer"),
        }
    }

    /// `FieldByIndex(index)` — nested field access by index path.
    /// Mirrors Go's `Value.FieldByIndex`. Walks struct → struct → ...
    pub fn FieldByIndex(&self, index: &[int]) -> Value {
        let mut v = self.clone();
        for (i, &x) in index.iter().enumerate() {
            if i > 0 {
                if let Value::Pointer(_) = v {
                    v = v.Elem();
                }
            }
            v = v.Field(x);
        }
        v
    }

    /// `OverflowInt(x)` — true if `x` cannot be represented in this
    /// signed-int Value's type. Mirrors Go's bit-shift truncation test.
    pub fn OverflowInt(&self, x: int) -> bool {
        let bit_size = match self.Kind() {
            Kind::Int => 64,
            Kind::Int8 => 8,
            Kind::Int16 => 16,
            Kind::Int32 => 32,
            _ => panic!("reflect.Value.OverflowInt of non-int"),
        };
        if bit_size == 64 {
            return false;
        }
        let shift = 64 - bit_size;
        let trunc = (x << shift) >> shift;
        x != trunc
    }

    /// `OverflowUint(x)` — counterpart of `OverflowInt` for unsigned.
    pub fn OverflowUint(&self, x: uint) -> bool {
        let bit_size = match self.Kind() {
            Kind::Uint => 64,
            Kind::Uint8 => 8,
            Kind::Uint16 => 16,
            Kind::Uint32 => 32,
            _ => panic!("reflect.Value.OverflowUint of non-uint"),
        };
        if bit_size == 64 {
            return false;
        }
        let shift = 64 - bit_size;
        let trunc = (x << shift) >> shift;
        x != trunc
    }

    /// `OverflowFloat(x)` — true if `x` cannot be represented in this
    /// float Value's type without loss of magnitude.
    pub fn OverflowFloat(&self, x: float64) -> bool {
        match self.Kind() {
            Kind::Float64 => false,
            Kind::Float32 => {
                let ax = if x < 0.0 { -x } else { x };
                ax > float32::MAX as float64
            }
            _ => panic!("reflect.Value.OverflowFloat of non-float"),
        }
    }

    /// `MapKeys()` — keys in stable (sorted) order, as `slice<Value>`
    /// (Go's `[]Value`). Panics if not Map.
    pub fn MapKeys(&self) -> crate::goslice::slice<Value> {
        if let Value::Named { inner, .. } = self {
            return inner.MapKeys();
        }
        match self {
            Value::Map { entries, .. } => {
                let v: Vec<Value> = entries.iter().map(|(k, _)| k.clone()).collect();
                crate::goslice::slice::__from_vec(v)
            }
            _ => panic!("reflect.Value.MapKeys of non-map"),
        }
    }

    /// `MapIndex(key)` — value for key, or `Value::Invalid` if absent.
    /// Linear scan for v1 (entries are sorted; we could binary-search
    /// over comparable keys, but v1 keeps it straightforward).
    pub fn MapIndex(&self, key: &Value) -> Value {
        if let Value::Named { inner, .. } = self {
            return inner.MapIndex(key);
        }
        match self {
            Value::Map { entries, .. } => {
                for (k, v) in entries {
                    if value_eq(k, key) {
                        return v.clone();
                    }
                }
                Value::Invalid
            }
            _ => panic!("reflect.Value.MapIndex of non-map"),
        }
    }

    /// `Index(i)` — i-th element of a slice. Panics if not Slice.
    pub fn Index(&self, i: int) -> Value {
        if let Value::Named { inner, .. } = self {
            return inner.Index(i);
        }
        match self {
            Value::Slice { items, .. } => items[i as usize].clone(),
            _ => panic!("reflect.Value.Index of non-slice"),
        }
    }

    /// `NumField()` — struct field count. Panics if not Struct.
    pub fn NumField(&self) -> int {
        match self {
            Value::Struct { ty, .. } => ty.NumField(),
            _ => panic!("reflect.Value.NumField of non-struct"),
        }
    }

    /// `Field(i)` — i-th field of a struct. Panics if not Struct.
    pub fn Field(&self, i: int) -> Value {
        match self {
            Value::Struct { fields, .. } => fields[i as usize].clone(),
            _ => panic!("reflect.Value.Field of non-struct"),
        }
    }

    /// `FieldByName(name)` — looks up by name. Returns `Value::Invalid`
    /// if not found.
    pub fn FieldByName(&self, name: &str) -> Value {
        match self {
            Value::Struct { ty, fields } => {
                for i in 0..ty.fields.len() {
                    if ty.fields[i].Name.as_bytes() == name.as_bytes() {
                        return fields[i].clone();
                    }
                }
                Value::Invalid
            }
            _ => panic!("reflect.Value.FieldByName of non-struct"),
        }
    }

    /// `CanInterface()` — whether `Interface()` is callable without panic.
    ///
    /// Go's semantics also returns false for unexported struct fields
    /// accessed via reflection; goish v1 does not track export status
    /// per Value, so we conservatively return true for every valid
    /// Value. Ports using this as a `Interface()` precondition (e.g.
    /// kylelemons pretty-printer) get the same outcome as Go.
    pub fn CanInterface(&self) -> bool {
        self.IsValid()
    }

    /// `Pointer()` — address as uintptr.
    ///
    /// Goish v1's `Value` is owned-tree-shaped, not pointer-shaped, so
    /// no real machine address exists for primitive variants. For
    /// `Value::Pointer(b)` we return the stable address of the boxed
    /// inner (valid for `self`'s lifetime). For other kinds we return
    /// 0. Sufficient for cycle-detection patterns (kylelemons walks
    /// pointer values to detect cycles); semantically degraded vs. Go
    /// for callers that round-trip through pointer arithmetic.
    pub fn Pointer(&self) -> uintptr {
        match self {
            Value::Pointer(b) => (&**b as *const Value) as uintptr,
            _ => 0,
        }
    }

    /// `Complex()` — `complex128` accessor.
    ///
    /// Goish v1 has no complex variant on `Value` (Kind::Complex64/128
    /// exist only for match-arm parity). Returns `(0.0, 0.0)` so
    /// format-only call sites compile. Real complex arithmetic is not
    /// supported in v1 — a port that does math on the result must be
    /// hand-tuned.
    pub fn Complex(&self) -> complex128 {
        (0.0, 0.0)
    }

    /// `Call(args)` — invoke a `Kind::Func` value with the given args.
    ///
    /// Goish v1's `Value` does not model `Kind::Func` (functions
    /// aren't introspectable via reflection in v1). Always returns an
    /// empty result slice. Ports that rely on dynamic reflective
    /// dispatch (e.g. kylelemons calling a user-supplied `Formatter`)
    /// fall through to the non-reflect path — visible behaviour is a
    /// no-op, not a panic.
    pub fn Call(&self, _args: crate::goslice::slice<Value>) -> crate::goslice::slice<Value> {
        crate::goslice::slice::default()
    }
}

/// Structural equality for use by `MapIndex`. Compares by Kind and
/// payload. Sufficient for json-shaped lookups (string keys); for
/// general use the `reflect.DeepEqual` port (later iteration) will be
/// the public API.
fn value_eq(a: &Value, b: &Value) -> bool {
    match (a, b) {
        (Value::Invalid, Value::Invalid) => true,
        (Value::Bool(x), Value::Bool(y)) => x == y,
        (Value::Int(x), Value::Int(y)) => x == y,
        (Value::Int8(x), Value::Int8(y)) => x == y,
        (Value::Int16(x), Value::Int16(y)) => x == y,
        (Value::Int32(x), Value::Int32(y)) => x == y,
        (Value::Uint(x), Value::Uint(y)) => x == y,
        (Value::Uint8(x), Value::Uint8(y)) => x == y,
        (Value::Uint16(x), Value::Uint16(y)) => x == y,
        (Value::Uint32(x), Value::Uint32(y)) => x == y,
        (Value::Float32(x), Value::Float32(y)) => x == y,
        (Value::Float64(x), Value::Float64(y)) => x == y,
        (Value::String(x), Value::String(y)) => x == y,
        _ => false,
    }
}

