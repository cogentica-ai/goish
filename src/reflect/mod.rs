// ─── Kind ─────────────────────────────────────────────────────────────

/// Mirrors `reflect.Kind`. Numeric ordering matches Go where possible
/// (Invalid = 0; Bool = 1; …) so debug-printing comes out the same.
// Goish v1's `Kind` keeps the original numbering (Invalid=0, Bool=1, …)
// — predates the full Go variant list. Variants added incrementally as
// ports surface them. Where a Go variant has no goish backing type yet
// (Complex64/128, Array stays as a stub), the variant is present so
// match arms compile, but `__reflect_value` never produces it.
#[repr(u8)]
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum Kind {
    #[default]
    Invalid = 0,
    Bool = 1,
    Int = 2,
    Int8 = 3,
    Int16 = 4,
    Int32 = 5,
    Uint = 6,
    Uint8 = 7,
    Uint16 = 8,
    Uint32 = 9,
    Float32 = 10,
    Float64 = 11,
    String = 12,
    Slice = 13,
    Map = 14,
    Struct = 15,
    Pointer = 16,
    /// Go's `reflect.Interface` (Kind 20). For `any`-typed values whose
    /// dynamic type is opaque from the static descriptor — `__reflect_value`
    /// runtime-downcasts to fill in concrete `Value` variants.
    Interface = 17,
    /// Go: `reflect.Int64`. Goish stores int as i64 so Kind::Int and
    /// Kind::Int64 both apply to int values; ports differentiate via
    /// the explicit type only.
    Int64 = 18,
    /// Go: `reflect.Uint64`. Same convention as Int64.
    Uint64 = 19,
    /// Go: `reflect.Uintptr`. Goish v1 has no `uintptr` distinct from
    /// `uint`; the variant exists so reflect-driven match arms compile.
    Uintptr = 20,
    /// Go: `reflect.Func`. Function-typed values; goish stores as
    /// `Arc<dyn Fn>` and `__reflect_value` returns `Value::Invalid` for
    /// these (we don't introspect callable shapes).
    Func = 21,
    /// Go: `reflect.Chan`. Channels; v1 reflect doesn't introspect.
    Chan = 22,
    /// Go: `reflect.UnsafePointer`. Goish has no `unsafe.Pointer` API;
    /// the variant exists for match-arm parity.
    UnsafePointer = 23,
    /// Go: `reflect.Array`. Fixed-size arrays. Goish slices satisfy
    /// most uses; Kind::Array exists for parity but `__reflect_value`
    /// produces Slice instead.
    Array = 24,
    /// Go: `reflect.Complex64`. Goish has no native complex arithmetic;
    /// `__reflect_value` never produces this variant — it exists so
    /// match arms on Kind compile in ports that mention complex.
    Complex64 = 25,
    /// Go: `reflect.Complex128`. Same caveat as Complex64.
    Complex128 = 26,
}

