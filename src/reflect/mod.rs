// go: package reflect
// reflect — Go's `reflect` package, first slice.
//
//   Go                                   goish
//   ──────────────────────────────────   ──────────────────────────────────
//   t := reflect.TypeOf(p)               let t = reflect::TypeOf(&p);
//   t.Name()                             t.Name()
//   t.Kind()                             t.Kind()
//   t.NumField()                         t.NumField()
//   f := t.Field(0)                      let f = t.Field(0);
//   f.Name                               f.Name
//   f.Tag.Get("json")                    f.Tag.Get("json")
//   v, ok := f.Tag.Lookup("xml")         let (v, ok) = f.Tag.Lookup("xml");
//
// Backing: per-struct static `Type` descriptors generated by the
// `#[goish::reflect]` proc-macro. Built-in primitives (bool, int, byte,
// rune, uint, float32, float64, string) get `Reflect` impls in this file.
//
// First slice covers Type/StructField/StructTag and their accessors.
// `Value` (actual data introspection), generic Reflect for slice/map,
// and json integration follow in later iterations.
//
// v1 deviations from Go:
//
//   * `Kind::Int` corresponds to i64 (= goish `int`); there's no separate
//     `Kind::Int64` because `int` IS `i64`. Same for `Kind::Uint` (= u64).
//   * `StructField.Type` is `fn() -> Type` (late binding). Go's
//     `StructField.Type` is a `reflect.Type` interface value, evaluated
//     lazily under the hood. Goish uses the explicit fn-pointer form.
//   * `Reflect` is an opt-in trait. User structs add `#[goish::reflect]`;
//     primitives have impls in this file. Convention: every goish-defined
//     `type X struct` should carry `#[goish::reflect]`.

