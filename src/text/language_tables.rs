// go: none — goish-only: x/text reads `langNoIndex` through
// `internal/language.getLangISO3`, which has no goish counterpart
// because goish keys by string rather than by compact id.
/// True if `code` is an accepted three-letter base language.
///
/// Indexes the bitmap above. A byte outside `a..=z` returns false rather
/// than indexing anywhere — the parser checks `is_alpha` first, but a
/// table helper that trusts its caller for memory safety is one
/// refactor away from being wrong.
pub(super) fn lang3_accepted(code: &str) -> bool {
    let b = code.as_bytes();
    if b.len() != 3 {
        return false;
    }
    let mut idx: usize = 0;
    let mut mul: usize = 676;
    let mut i = 0usize;
    while i < 3 {
        let c = b[i];
        if c < b'a' || c > b'z' {
            return false;
        }
        idx += (c - b'a') as usize * mul;
        mul /= 26;
        i += 1;
    }
    return LANG3_ACCEPTED[idx >> 3] & (1u8 << (idx & 7)) != 0;
}
