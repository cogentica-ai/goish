/// Encrypt a plaintext message.
///
/// It implements K-PKE.Encrypt according to FIPS 203, Algorithm 14,
/// although the computation of t and AT is done in parseEK1024.
fn pkeEncrypt1024(
    cc: &mut [byte; CiphertextSize1024],
    ex: &encryptionKey1024,
    m: &[byte; messageSize],
    rnd: &[byte],
) -> slice<byte> {
    // Go: var N byte; r, e1 := make([]nttElement, k1024), make([]ringElement, k1024)
    let mut N: byte = 0;
    let mut r = [zeroNTT1024(); k1024];
    let mut e1 = [ringElement([0; n]); k1024];
    // Go: for i := range r { r[i] = ntt(samplePolyCBD(rnd, N)); N++ }
    let mut i: usize = 0;
    while i < k1024 {
        r[i] = ntt(samplePolyCBD(rnd, N));
        N += 1;
        i += 1;
    }
    // Go: for i := range e1 { e1[i] = samplePolyCBD(rnd, N); N++ }
    let mut i: usize = 0;
    while i < k1024 {
        e1[i] = samplePolyCBD(rnd, N);
        N += 1;
        i += 1;
    }
    // Go: e2 := samplePolyCBD(rnd, N)
    let e2 = samplePolyCBD(rnd, N);

    // Go: u := make([]ringElement, k1024) // NTT⁻¹(AT ◦ r) + e1
    let mut u = [ringElement([0; n]); k1024];
    let mut i: usize = 0;
    while i < k1024 {
        u[i] = e1[i];
        let mut j: usize = 0;
        while j < k1024 {
            // Note that i and j are inverted, as we need the transposed of A.
            u[i] = polyAdd(u[i], inverseNTT(nttMul(ex.a[j * k1024 + i], r[j])));
            j += 1;
        }
        i += 1;
    }

    // Go: μ := ringDecodeAndDecompress1(m)
    let μ = ringDecodeAndDecompress1(m);

    // Go: var vNTT nttElement // t⊺ ◦ r
    //     for i := range ex.t { vNTT = polyAdd(vNTT, nttMul(ex.t[i], r[i])) }
    let mut vNTT = zeroNTT1024();
    let mut i: usize = 0;
    while i < k1024 {
        vNTT = polyAdd(vNTT, nttMul(ex.t[i], r[i]));
        i += 1;
    }
    // Go: v := polyAdd(polyAdd(inverseNTT(vNTT), e2), μ)
    let v = polyAdd(polyAdd(inverseNTT(vNTT), e2), μ);

    // Go: c := cc[:0]
    //     for _, f := range u { c = ringCompressAndEncode11(c, f) }
    //     c = ringCompressAndEncode5(c, v)
    let mut c = empty1024();
    let mut i: usize = 0;
    while i < k1024 {
        c = ringCompressAndEncode11(c, u[i]);
        i += 1;
    }
    c = ringCompressAndEncode5(c, v);

    // Go writes through `cc[:0]`, so the caller's array holds the result;
    // goish's slices don't alias, so fill it explicitly.
    let cr: &[byte] = &c;
    cc.copy_from_slice(cr);
    return c;
}

