/// Decrypt a ciphertext.
///
/// It implements K-PKE.Decrypt according to FIPS 203, Algorithm 15,
/// although s is retained from kemKeyGen1024.
fn pkeDecrypt1024(dx: &decryptionKey1024, c: &[byte; CiphertextSize1024]) -> slice<byte> {
    // Go: u := make([]ringElement, k1024)
    //     for i := range u { b := (*[encodingSize11]byte)(c[…]); u[i] = ringDecodeAndDecompress11(b) }
    let mut u = [ringElement([0; n]); k1024];
    let mut i: usize = 0;
    while i < k1024 {
        let mut b = [0u8; encodingSize11];
        b.copy_from_slice(&c[encodingSize11 * i..encodingSize11 * (i + 1)]);
        u[i] = ringDecodeAndDecompress11(&b);
        i += 1;
    }

    // Go: b := (*[encodingSize5]byte)(c[encodingSize11*k1024:]); v := ringDecodeAndDecompress5(b)
    let mut b = [0u8; encodingSize5];
    b.copy_from_slice(&c[encodingSize11 * k1024..]);
    let v = ringDecodeAndDecompress5(&b);

    // Go: var mask nttElement // s⊺ ◦ NTT(u)
    //     for i := range dx.s { mask = polyAdd(mask, nttMul(dx.s[i], ntt(u[i]))) }
    let mut mask = zeroNTT1024();
    let mut i: usize = 0;
    while i < k1024 {
        mask = polyAdd(mask, nttMul(dx.s[i], ntt(u[i])));
        i += 1;
    }
    // Go: w := polySub(v, inverseNTT(mask))
    let w = polySub(v, inverseNTT(mask));

    // Go: return ringCompressAndEncode1(nil, w)
    return ringCompressAndEncode1(empty1024(), w);
}
