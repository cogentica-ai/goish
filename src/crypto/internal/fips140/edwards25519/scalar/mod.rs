/// LEUint64 — decode a little-endian uint64 from an 8-byte window.
fn LEUint64(b: &[byte]) -> u64 {
    let mut arr = [0u8; 8];
    arr.copy_from_slice(&b[0..8]);
    u64::from_le_bytes(arr)
}

