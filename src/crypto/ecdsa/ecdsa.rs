// go: none — Go's `switch curve { case elliptic.P256(): … }` compares
// interface values: same dynamic type AND same pointer. Comparing the data
// half of goish's fat pointer is that same test, and it keeps
// `elliptic::P256()` distinct from a `CurveParams` with identical fields —
// which is the distinction Go relies on for `PublicKey.Equal`.
fn sameCurve(
    a: &(dyn elliptic::Curve + Send + Sync),
    b: &(dyn elliptic::Curve + Send + Sync),
) -> bool {
    return core::ptr::eq(a as *const _ as *const (), b as *const _ as *const ());
}

// go: none — the `switch c.Params()` sites compare CurveParams *by value*.
// Among the four NIST curves the canonical name is the discriminator, and
// it is what `sameParams` compares first.
fn curveName(c: &(dyn elliptic::Curve + Send + Sync)) -> string {
    return c.Params().Name;
}

