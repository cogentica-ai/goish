/// Parse a public key encoded as an uncompressed point according to SEC 1,
/// Version 2.0, Section 2.3.3 (also known as the X9.62 uncompressed
/// format). Returns an error if the point is not in uncompressed form, is
/// not on the curve, or is the point at infinity.
///
/// `curve` must be one of `elliptic::P224`, `elliptic::P256`,
/// `elliptic::P384` or `elliptic::P521`, or an error is returned.
pub fn ParseUncompressedPublicKey(
    curve: &'static (dyn elliptic::Curve + Send + Sync),
    data: &slice<byte>,
) -> (PublicKey, error) {
    let d: &[byte] = data;
    if d.len() < 1 || d[0] != 4 {
        return (
            zeroPublicKey(),
            errors::New("ecdsa: invalid uncompressed public key"),
        );
    }
    if sameCurve(curve, elliptic::P224()) {
        return parseUncompressedPublicKey(fipsec::P224(), curve, data);
    }
    if sameCurve(curve, elliptic::P256()) {
        return parseUncompressedPublicKey(fipsec::P256(), curve, data);
    }
    if sameCurve(curve, elliptic::P384()) {
        return parseUncompressedPublicKey(fipsec::P384(), curve, data);
    }
    if sameCurve(curve, elliptic::P521()) {
        return parseUncompressedPublicKey(fipsec::P521(), curve, data);
    }
    return (
        zeroPublicKey(),
        errors::New("ecdsa: curve not supported by ParseUncompressedPublicKey"),
    );
}

