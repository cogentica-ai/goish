/// Parse a private key encoded as a fixed-length big-endian integer,
/// according to SEC 1, Version 2.0, Section 2.3.6 (sometimes referred to as
/// the raw format). Returns an error if the value is not reduced modulo the
/// curve's order, or if it's zero.
pub fn ParseRawPrivateKey(
    curve: &'static (dyn elliptic::Curve + Send + Sync),
    data: &slice<byte>,
) -> (PrivateKey, error) {
    if sameCurve(curve, elliptic::P224()) {
        return parseRawPrivateKey(fipsec::P224(), nistec::NewP224Point, curve, data);
    }
    if sameCurve(curve, elliptic::P256()) {
        return parseRawPrivateKey(fipsec::P256(), nistec::NewP256Point, curve, data);
    }
    if sameCurve(curve, elliptic::P384()) {
        return parseRawPrivateKey(fipsec::P384(), nistec::NewP384Point, curve, data);
    }
    if sameCurve(curve, elliptic::P521()) {
        return parseRawPrivateKey(fipsec::P521(), nistec::NewP521Point, curve, data);
    }
    return (
        zeroPrivateKey(),
        errors::New("ecdsa: curve not supported by ParseRawPrivateKey"),
    );
}

