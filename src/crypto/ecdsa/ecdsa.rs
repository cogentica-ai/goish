    fips140cache::Cache::New();

// go: sdk 1.25.5 crypto/ecdsa/ecdsa.go:578-589 privateKeyToFIPS
fn privateKeyToFIPS<P: fipsec::Point>(
    c: &fipsec::Curve<P>,
    priv_: &PrivateKey,
) -> (fipsec::PrivateKey, error) {
    let (Q, err) = pointFromAffine(
        priv_.PublicKey.Curve,
        &priv_.PublicKey.X,
        &priv_.PublicKey.Y,
    );
    if err != nil {
        return (fipsec::PrivateKey::default(), err);
    }
    let Qc = Q.clone();
    return privateKeyCache.Get(
        priv_,
        || {
            return fipsec::NewPrivateKey(c, &priv_.D.Bytes(), &Q);
        },
        |k: &fipsec::PrivateKey| {
            return subtle::ConstantTimeCompare(&k.PublicKey().Bytes(), &Qc) == 1
                && leftPadBytesEqual(&k.Bytes(), &priv_.D.Bytes());
        },
    );
}

// go: sdk 1.25.5 crypto/ecdsa/ecdsa.go:591-603 leftPadBytesEqual
fn leftPadBytesEqual(a: &slice<byte>, b: &slice<byte>) -> bool {
    let (mut a, mut b): (&[byte], &[byte]) = (a, b);
    if a.len() < b.len() {
        core::mem::swap(&mut a, &mut b);
    }
    let padded: Vec<byte>;
    if a.len() > b.len() {
        // Go: enough for a P-521 private key.
        let mut x: Vec<byte> = Vec::with_capacity(66);
        x.extend(core::iter::repeat(0u8).take(a.len() - b.len()));
        x.extend_from_slice(b);
        padded = x;
        b = &padded;
    }
    return subtle::ConstantTimeCompare(
        &slice::__from_vec(a.to_vec()),
        &slice::__from_vec(b.to_vec()),
    ) == 1;
}

// go: sdk 1.25.5 crypto/ecdsa/ecdsa.go:605-622 pointFromAffine
/// Convert the PublicKey to a nistec SetBytes input.
fn pointFromAffine(
    curve: &(dyn elliptic::Curve + Send + Sync),
    x: &Int,
    y: &Int,
) -> (slice<byte>, error) {
    let bitSize = curve.Params().BitSize;
    // Reject values that would not get correctly encoded.
    if x.Sign() < 0 || y.Sign() < 0 {
        return (empty(), errors::New("negative coordinate"));
    }
    if x.BitLen() > bitSize || y.BitLen() > bitSize {
        return (empty(), errors::New("overflowing coordinate"));
    }
    // Encode the coordinates and let SetBytes reject invalid points.
    let byteLen = (bitSize + 7) / 8;
    let mut buf: Vec<byte> = alloc::vec![0u8; 1 + 2 * (byteLen as usize)];
    buf[0] = 4; // uncompressed point
    let xb = x.FillBytes(zeros(byteLen));
    let yb = y.FillBytes(zeros(byteLen));
    let (xr, yr): (&[byte], &[byte]) = (&xb, &yb);
    let n = byteLen as usize;
    buf[1..1 + n].copy_from_slice(xr);
    buf[1 + n..1 + 2 * n].copy_from_slice(yr);
    return (slice::__from_vec(buf), nil);
}

// go: sdk 1.25.5 crypto/ecdsa/ecdsa.go:624-633 pointToAffine
/// Convert a nistec Bytes encoding to a PublicKey.
fn pointToAffine(
    curve: &(dyn elliptic::Curve + Send + Sync),
    p: &slice<byte>,
) -> (Int, Int, error) {
    let raw: &[byte] = p;
    if raw.len() == 1 && raw[0] == 0 {
        // This is the encoding of the point at infinity.
        return (
            Int::default(),
            Int::default(),
            errors::New("ecdsa: public key point is the infinity"),
        );
    }
    let byteLen = ((curve.Params().BitSize + 7) / 8) as usize;
    let mut x = Int::default();
    let mut y = Int::default();
    x.SetBytes(slice::__from_vec(raw[1..1 + byteLen].to_vec()));
    y.SetBytes(slice::__from_vec(raw[1 + byteLen..].to_vec()));
    return (x, y, nil);
}

