//
// Package ecdsa implements the Elliptic Curve Digital Signature Algorithm,
// as defined in FIPS 186-5.
//
// Signatures generated by this package are not deterministic, but entropy
// is mixed with the private key and the message, achieving the same level
// of security in case of randomness source failure.
//
// Operations involving private keys are implemented using constant-time
// algorithms, as long as an `elliptic.Curve` returned by `elliptic::P224`,
// `elliptic::P256`, `elliptic::P384` or `elliptic::P521` is used.
//
// Deviations from ecdsa[go] @ Go 1.25.5:
//
//   * Go embeds `elliptic.Curve` in PublicKey and `PublicKey` in
//     PrivateKey. goish has no embedding, so both are named fields —
//     `pub.Curve` and `priv.PublicKey`, which is how Go's promotion reads
//     anyway (AGENTS.md §5).
//   * `rand io.Reader` is nilable at two call sites (`PrivateKey.Sign`
//     switches on it), and `opts crypto.SignerOpts` is nil-checked in
//     `signRFC6979`. Both become `Option<&mut …>` / `Option<&…>`, the
//     shape crypto/rsa already uses for a nilable Go interface argument.
//   * Go returns a nil `*PublicKey` / `*PrivateKey` on every error path.
//     goish returns a zero value paired with the error, and both types get
//     `PartialEq<Nil>` so `k == nil` still reads the same (cf. crypto/rsa).
//   * `switch curve { case elliptic.P256(): … }` is Go *interface
//     identity*: `elliptic.P256()` and `elliptic.P256().Params()` are
//     different values and the latter falls to default. goish compares the
//     data half of the fat pointer, which is exactly that test — see
//     `sameCurve`. The `switch c.Params()` sites compare by value instead,
//     and there `curveName` is the discriminator.
//   * `boring.*` is dropped throughout, as everywhere else in the tree;
//     the two stubs live in notboring.rs.

