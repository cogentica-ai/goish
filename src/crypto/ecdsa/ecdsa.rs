// go: sdk 1.25.5 crypto/ecdsa/ecdsa.go:200-211 curveToECDH
fn curveToECDH(
    c: &(dyn elliptic::Curve + Send + Sync),
) -> Option<&'static (dyn ecdh::Curve + Send + Sync)> {
    if sameCurve(c, elliptic::P256()) {
        return Some(ecdh::P256());
    }
    if sameCurve(c, elliptic::P384()) {
        return Some(ecdh::P384());
    }
    if sameCurve(c, elliptic::P521()) {
        return Some(ecdh::P521());
    }
    return None;
}

