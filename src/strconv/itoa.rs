/// Enable the fast path for small integers.
pub(crate) const fastSmalls: bool = true;

// go: sdk 1.25.5 strconv/itoa.go:66-66 nSmalls
pub(crate) const nSmalls: int = 100;

// go: sdk 1.25.5 strconv/itoa.go:68-77 smallsString
/// The two-digit decimal renderings of 00..99, back to back. `small`
/// and the base-10 path of `formatBits` both index straight into it.
pub(crate) const smallsString: &[u8] = b"00010203040506070809\
10111213141516171819\
20212223242526272829\
30313233343536373839\
40414243444546474849\
50515253545556575859\
60616263646566676869\
70717273747576777879\
80818283848586878889\
90919293949596979899";

// go: sdk 1.25.5 strconv/itoa.go:79-79 host32bit
/// Go computes this as `^uint(0)>>32 == 0`. goish's `uint` is 64-bit on
/// every target it builds for, so the 32-bit lower-digit loop in
/// `formatBits` is compiled but never taken — kept so the two files
/// stay line-for-line comparable.
pub(crate) const host32bit: bool = (uint::MAX >> 32) == 0;

// go: sdk 1.25.5 strconv/itoa.go:81-81 digits
pub(crate) const digits: &[u8] = b"0123456789abcdefghijklmnopqrstuvwxyz";

