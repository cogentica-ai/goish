// go: sdk 1.25.5 strconv/itoa.go:88-194 formatBits
/// `formatBits` computes the string representation of `u` in the given
/// base. If `neg` is set, `u` is treated as a negative int64 value. If
/// `append_` is set the string is appended to `dst` and the resulting
/// byte slice is returned as the first result; otherwise the string is
/// returned as the second.
pub(crate) fn formatBits(
    dst: slice<byte>,
    mut u: uint,
    base: int,
    neg: bool,
    append_: bool,
) -> (slice<byte>, string) {
    if base < 2 || base > toint(digits.len()) {
        panic!("strconv: illegal AppendInt/FormatInt base");
    }
    // 2 <= base && base <= len(digits)

    let mut a = [0u8; 64 + 1]; // +1 for sign of 64bit value in base 2
    let mut i = a.len();

    if neg {
        u = u.wrapping_neg();
    }

    // convert bits
    // We use uint values where we can because those will
    // fit into a single register even on a 32bit machine.
    if base == 10 {
        // common case: use constants for / because
        // the compiler can optimize it into a multiply+shift

        if host32bit {
            // convert the lower digits using 32bit operations
            while u >= 1_000_000_000 {
                // Avoid using r = a%b in addition to q = a/b
                // since 64bit division and modulo operations
                // are calculated by runtime functions on 32bit machines.
                let q = u / 1_000_000_000;
                let mut us: uint = u - q * 1_000_000_000; // u % 1e9 fits into a uint
                let mut j = 4;
                while j > 0 {
                    let is = (us % 100 * 2) as usize;
                    us /= 100;
                    i -= 2;
                    a[i + 1] = smallsString[is + 1];
                    a[i] = smallsString[is];
                    j -= 1;
                }

                // us < 10, since it contains the last digit
                // from the initial 9-digit us.
                i -= 1;
                a[i] = smallsString[(us * 2 + 1) as usize];

                u = q;
            }
            // u < 1e9
        }

        // u guaranteed to fit into a uint
        let mut us: uint = u;
        while us >= 100 {
            let is = (us % 100 * 2) as usize;
            us /= 100;
            i -= 2;
            a[i + 1] = smallsString[is + 1];
            a[i] = smallsString[is];
        }

        // us < 100
        let is = (us * 2) as usize;
        i -= 1;
        a[i] = smallsString[is + 1];
        if us >= 10 {
            i -= 1;
            a[i] = smallsString[is];
        }
    } else if isPowerOfTwo(base) {
        // Use shifts and masks instead of / and %.
        let shift = touint(crate::math::bits::TrailingZeros(touint(base)));
        let b = touint64(base);
        let m = touint(base) - 1; // == 1<<shift - 1
        while u >= b {
            i -= 1;
            a[i] = digits[(u & m) as usize];
            u >>= shift;
        }
        // u < base
        i -= 1;
        a[i] = digits[u as usize];
    } else {
        // general case
        let b = touint64(base);
        while u >= b {
            i -= 1;
            // Avoid using r = a%b in addition to q = a/b
            // since 64bit division and modulo operations
            // are calculated by runtime functions on 32bit machines.
            let q = u / b;
            a[i] = digits[(u - q * b) as usize];
            u = q;
        }
        // u < base
        i -= 1;
        a[i] = digits[u as usize];
    }

    // add sign, if any
    if neg {
        i -= 1;
        a[i] = b'-';
    }

    if append_ {
        let mut v = dst.__into_vec();
        v.extend_from_slice(&a[i..]);
        return (slice::__from_vec(v), string::new());
    }
    return (slice::new(), string::from_bytes(&a[i..]));
}

// go: sdk 1.25.5 strconv/itoa.go:197-199 isPowerOfTwo
fn isPowerOfTwo(x: int) -> bool {
    return x & (x - 1) == 0;
}
