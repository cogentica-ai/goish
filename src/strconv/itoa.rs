// go: sdk 1.25.5 strconv/itoa.go:14-20 FormatUint
/// `strconv.FormatUint` — the string representation of `i` in the given
/// base, for 2 <= base <= 36, using lower-case letters for digit values
/// >= 10.
pub fn FormatUint(i: uint, base: int) -> string {
    if fastSmalls && i < touint(nSmalls) && base == 10 {
        return small(toint(i));
    }
    let (_, s) = formatBits(slice::new(), i, base, false, false);
    return s;
}

// go: sdk 1.25.5 strconv/itoa.go:25-31 FormatInt
/// `strconv.FormatInt` — the string representation of `i` in the given
/// base, for 2 <= base <= 36.
pub fn FormatInt(i: int, base: int) -> string {
    if fastSmalls && 0 <= i && i < nSmalls && base == 10 {
        return small(i);
    }
    let (_, s) = formatBits(slice::new(), touint64(i), base, i < 0, false);
    return s;
}

// go: sdk 1.25.5 strconv/itoa.go:34-36 Itoa
/// `strconv.Itoa` — equivalent to `FormatInt(int64(i), 10)`.
pub fn Itoa(i: int) -> string {
    return FormatInt(i, 10);
}

// go: sdk 1.25.5 strconv/itoa.go:40-46 AppendInt
/// `strconv.AppendInt` — append the string form of `i`, as generated by
/// `FormatInt`, to `dst`.
pub fn AppendInt(dst: slice<byte>, i: int, base: int) -> slice<byte> {
    if fastSmalls && 0 <= i && i < nSmalls && base == 10 {
        let mut v = dst.__into_vec();
        v.extend_from_slice(small(i).as_bytes());
        return slice::__from_vec(v);
    }
    let (d, _) = formatBits(dst, touint64(i), base, i < 0, true);
    return d;
}

// go: sdk 1.25.5 strconv/itoa.go:50-56 AppendUint
/// `strconv.AppendUint` — append the string form of `i`, as generated
/// by `FormatUint`, to `dst`.
pub fn AppendUint(dst: slice<byte>, i: uint, base: int) -> slice<byte> {
    if fastSmalls && i < touint(nSmalls) && base == 10 {
        let mut v = dst.__into_vec();
        v.extend_from_slice(small(toint(i)).as_bytes());
        return slice::__from_vec(v);
    }
    let (d, _) = formatBits(dst, i, base, false, true);
    return d;
}

// go: sdk 1.25.5 strconv/itoa.go:59-64 small
/// The string for an `i` with 0 <= i < nSmalls.
fn small(i: int) -> string {
    let i = i as usize;
    if i < 10 {
        return string::from_bytes(&digits[i..i + 1]);
    }
    return string::from_bytes(&smallsString[i * 2..i * 2 + 2]);
}

