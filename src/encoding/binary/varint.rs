// go: sdk 1.25.5 encoding/binary/varint.go:41-47 AppendUvarint
/// `binary.AppendUvarint(buf, x)` — append the varint-encoded form of
/// `x`, as generated by [`PutUvarint`], to `buf` and return the
/// extended buffer.
pub fn AppendUvarint(buf: slice<byte>, x: uint) -> slice<byte> {
    let mut x = x;
    let mut out: Vec<byte> = buf.__into_vec();
    // Go: for x >= 0x80 { buf = append(buf, byte(x)|0x80); x >>= 7 }
    while x >= 0x80 {
        out.push(tobyte(x) | 0x80);
        x >>= 7;
    }
    // Go: return append(buf, byte(x))
    out.push(tobyte(x));
    return slice::__from_vec(out);
}

// go: sdk 1.25.5 encoding/binary/varint.go:51-60 PutUvarint
/// `binary.PutUvarint(buf, x)` — encode `x` into `buf` and return the
/// number of bytes written. Panics if the buffer is too small.
pub fn PutUvarint(buf: &mut slice<byte>, x: uint) -> int {
    let mut x = x;
    // Go: i := 0
    let mut i: int = 0;
    // Go: for x >= 0x80 { buf[i] = byte(x) | 0x80; x >>= 7; i++ }
    while x >= 0x80 {
        buf[i] = tobyte(x) | 0x80;
        x >>= 7;
        i += 1;
    }
    // Go: buf[i] = byte(x); return i + 1
    buf[i] = tobyte(x);
    return i + 1;
}

// go: sdk 1.25.5 encoding/binary/varint.go:68-88 Uvarint
/// `binary.Uvarint(buf)` — decode a `uint64` from `buf` and return
/// that value and the number of bytes read (> 0). On error the value
/// is 0 and `n <= 0`: `n == 0` means `buf` was too small, `n < 0`
/// means the value was larger than 64 bits and `-n` is the number of
/// bytes read.
pub fn Uvarint(buf: slice<byte>) -> (uint, int) {
    // Go: var x uint64; var s uint
    let mut x: uint = 0;
    let mut s: uint = 0;
    let raw: &[byte] = &buf;
    // Go: for i, b := range buf
    let mut i: int = 0;
    while i < toint(raw.len()) {
        let b = raw[usize::try_from(i).unwrap_or(0)];
        // Go: if i == MaxVarintLen64 — catch byte reads past
        // MaxVarintLen64 (golang.org/issues/41185).
        if i == MaxVarintLen64 {
            return (0, -(i + 1));
        }
        // Go: if b < 0x80
        if b < 0x80 {
            // Go: if i == MaxVarintLen64-1 && b > 1 { return 0, -(i+1) }
            if i == MaxVarintLen64 - 1 && b > 1 {
                return (0, -(i + 1));
            }
            // Go: return x | uint64(b)<<s, i + 1
            return (x | (touint(b) << s), i + 1);
        }
        // Go: x |= uint64(b&0x7f) << s; s += 7
        x |= touint(b & 0x7f) << s;
        s += 7;
        i += 1;
    }
    // Go: return 0, 0
    return (0, 0);
}

// go: sdk 1.25.5 encoding/binary/varint.go:91-97 AppendVarint
/// `binary.AppendVarint(buf, x)` — append the varint-encoded form of
/// `x`, as generated by [`PutVarint`], to `buf` and return the
/// extended buffer.
pub fn AppendVarint(buf: slice<byte>, x: int) -> slice<byte> {
    // Go: ux := uint64(x) << 1; if x < 0 { ux = ^ux }
    let mut ux: uint = touint(x) << 1;
    if x < 0 {
        ux = !ux;
    }
    // Go: return AppendUvarint(buf, ux)
    return AppendUvarint(buf, ux);
}

