// go: sdk 1.25.5 encoding/binary/varint.go:130-153 ReadUvarint
/// `binary.ReadUvarint(r)` — read an encoded unsigned integer from `r`.
///
/// The error is `io::EOF` only if no bytes were read; an EOF after
/// some but not all of the bytes becomes `io::ErrUnexpectedEOF`.
pub fn ReadUvarint<R: io::ByteReader + ?Sized>(r: &mut R) -> (uint, error) {
    // Go: var x uint64; var s uint
    let mut x: uint = 0;
    let mut s: uint = 0;
    // Go: for i := 0; i < MaxVarintLen64; i++
    let mut i: int = 0;
    while i < MaxVarintLen64 {
        // Go: b, err := r.ReadByte()
        let (b, err) = r.ReadByte();
        if err != crate::nil {
            // Go: if i > 0 && err == io.EOF { err = io.ErrUnexpectedEOF }
            if i > 0 && err == io::EOF {
                return (x, io::ErrUnexpectedEOF.into());
            }
            return (x, err);
        }
        // Go: if b < 0x80
        if b < 0x80 {
            // Go: if i == MaxVarintLen64-1 && b > 1 { return x, errOverflow }
            if i == MaxVarintLen64 - 1 && b > 1 {
                return (x, errOverflow.into());
            }
            // Go: return x | uint64(b)<<s, nil
            return (x | (touint(b) << s), crate::nil.into());
        }
        // Go: x |= uint64(b&0x7f) << s; s += 7
        x |= touint(b & 0x7f) << s;
        s += 7;
        i += 1;
    }
    // Go: return x, errOverflow
    return (x, errOverflow.into());
}

// go: sdk 1.25.5 encoding/binary/varint.go:157-164 ReadVarint
/// `binary.ReadVarint(r)` — read an encoded signed integer from `r`,
/// with the same error conventions as [`ReadUvarint`].
pub fn ReadVarint<R: io::ByteReader + ?Sized>(r: &mut R) -> (int, error) {
    // Go: ux, err := ReadUvarint(r) — ok to continue in presence of error.
    let (ux, err) = ReadUvarint(r);
    // Go: x := int64(ux >> 1); if ux&1 != 0 { x = ^x }
    let mut x: int = toint(ux >> 1);
    if (ux & 1) != 0 {
        x = !x;
    }
    return (x, err);
}
