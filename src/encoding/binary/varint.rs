pub fn PutVarint(buf: &mut slice<byte>, x: int) -> int {
    // Go: ux := uint64(x) << 1; if x < 0 { ux = ^ux }
    let mut ux: uint = touint(x) << 1;
    if x < 0 {
        ux = !ux;
    }
    // Go: return PutUvarint(buf, ux)
    return PutUvarint(buf, ux);
}

// go: sdk 1.25.5 encoding/binary/varint.go:115-122 Varint
/// `binary.Varint(buf)` — decode an `int64` from `buf`, with the same
/// `n` conventions as [`Uvarint`].
pub fn Varint(buf: slice<byte>) -> (int, int) {
    // Go: ux, n := Uvarint(buf) — ok to continue in presence of error.
    let (ux, n) = Uvarint(buf);
    // Go: x := int64(ux >> 1); if ux&1 != 0 { x = ^x }
    let mut x: int = toint(ux >> 1);
    if (ux & 1) != 0 {
        x = !x;
    }
    return (x, n);
}

