//
// The `decls:` manifest above lists varint.go's funcs only. GOISH017
// matches a manifest entry against Rust `fn` items, so naming
// `MaxVarintLen16`/`32`/`64` or `errOverflow` there would report all
// four as dropped ports. They are not dropped — each carries its own
// `// go: sdk` anchor below.
//
// encoding/binary/varint.go — variable-length integers.
//
// Unsigned integers are LEB128: seven bits of payload per byte, low
// group first, with the high bit set on every byte but the last.
// Signed integers are zig-zagged into that same encoding first —
// `x<<1`, complemented when negative — so that small magnitudes of
// either sign stay short, which a two's-complement `int64` would not.
//
// The overflow rule is the subtle part and is Go's, not a
// simplification. A 64-bit value needs at most ten groups, and the
// tenth carries only one usable bit, so a tenth byte greater than 1
// overflows even though it is a well-formed terminator. `Uvarint`
// also refuses to look at an eleventh byte at all (golang.org/issue/41185):
// reading it would be a buffer read past the longest legal encoding.
//
// Deviations from Go:
//
//   * `PutUvarint`/`PutVarint` take `&mut slice<byte>`. Go's `[]byte`
//     header points at a shared backing array, so a by-value parameter
//     still writes through to the caller; goish's `slice<byte>` owns
//     its buffer, and a by-value parameter would write to a copy that
//     is then dropped.
//   * `ReadUvarint`/`ReadVarint` take `&mut impl io::ByteReader`
//     rather than the `io.ByteReader` interface value, so a concrete
//     reader can be passed without boxing.

