#[goish::main]
fn main() {
    let mut failed = 0;

    // 1. Every pattern Go compiles, goish compiles too — except the
    //    three it documents as unsupported, which must FAIL, not
    //    silently accept.
    {
        let mut ok = true;
        let mut pi = 0usize;
        while pi < PATS.len() {
            let (_, err) = regexp::Compile(PATS[pi]);
            let mut unsupported = false;
            let mut u = 0usize;
            while u < UNSUPPORTED.len() {
                if UNSUPPORTED[u] == pi {
                    unsupported = true;
                }
                u += 1;
            }
            let want_ok = GO_COMPILES[pi] && !unsupported;
            if err.IsNil() != want_ok {
                fmt::Println!(
                    "   ",
                    s(PATS[pi]),
                    "go_compiles",
                    GO_COMPILES[pi],
                    "unsupported",
                    unsupported,
                    "goish_err",
                    if err.IsNil() { s("<nil>") } else { err.Error() }
                );
                ok = false;
            }
            pi += 1;
        }
        report(
            &mut failed,
            ok,
            " 1",
            "compile: accepts and rejects as Go does",
        );
    }

    // 2. Every submatch of every (pattern, input) pair Go compiled and
    //    goish accepts: 2170 answers, compared group by group.
    {
        let mut ok = true;
        let mut bad = 0;
        let mut i = 0usize;
        while i < WANT.len() {
            let (pi, si, want) = WANT[i];
            let mut unsupported = false;
            let mut u = 0usize;
            while u < UNSUPPORTED.len() {
                if UNSUPPORTED[u] == pi {
                    unsupported = true;
                }
                u += 1;
            }
            if unsupported {
                i += 1;
                continue;
            }
            let (re, err) = regexp::Compile(PATS[pi]);
            if !err.IsNil() {
                i += 1;
                continue;
            }
            let got = re.FindStringSubmatch(INPUTS[si]);
            let mut row_ok = got.Len() as usize == want.len();
            if row_ok {
                let mut k = 0usize;
                while k < want.len() {
                    if got[k as int] != s(want[k]) {
                        row_ok = false;
                    }
                    k += 1;
                }
            }
            if !row_ok {
                if bad < 8 {
                    fmt::Println!(
                        "   pat",
                        s(PATS[pi]),
                        "in",
                        fmt::Sprintf!("%q", s(INPUTS[si])),
                        "want",
                        want.len() as int,
                        "got",
                        got.Len()
                    );
                }
                bad += 1;
                ok = false;
            }
            i += 1;
        }
        if bad > 0 {
            fmt::Println!("   ", bad, "mismatches");
        }
        report(&mut failed, ok, " 2", "every submatch of every pair");
    }

    // 3. The rune boundary, called out on its own because it is the one
    //    that could hand a caller half a character.
    {
        let mut ok = true;
        let re = regexp::MustCompile(".");
        if re.FindStringSubmatch("日本語")[0] != s("日") {
            ok = false;
        }
        let neg = regexp::MustCompile("[^abc]");
        if neg.FindStringSubmatch("日本語")[0] != s("日") {
            ok = false;
        }
        let d = regexp::MustCompile("\\D");
        if d.FindStringSubmatch("日本語")[0] != s("日") {
            ok = false;
        }
        // A class range compares RUNES: [あ-ん] does not contain 日.
        let cls = regexp::MustCompile("[あ-ん]");
        if cls.FindStringSubmatch("日本語").Len() != 0 {
            ok = false;
        }
        if cls.FindStringSubmatch("aあb")[0] != s("あ") {
            ok = false;
        }
        // And `.` does not match a newline, which is Go's default.
        let dot = regexp::MustCompile(".");
        if dot.FindStringSubmatch("\n").Len() != 0 {
            ok = false;
        }
        let dots = regexp::MustCompile("(?s).");
        if dots.FindStringSubmatch("\n")[0] != s("\n") {
            ok = false;
        }
        report(&mut failed, ok, " 3", "one whole rune, never half of one");
    }

    if failed == 0 {
        fmt::Println!("ok 3/3");
        syscall::Exit(0);
    } else {
        fmt::Println!("FAIL", failed, "of 3");
        syscall::Exit(1);
    }
}
