// regexp_ref_smoke — the matcher against a running Go.
// (regexp/regexp.go, regexp/syntax/parse.go)
//
// Every expectation below is what a real Go 1.25.5 prints: the vectors
// are the output of `tools/gen_regexp_ref.go` run in `package
// regexp_test` by `scripts/goref.sh` — 70 patterns against 31 inputs,
// compared on the compile outcome and on every submatch.
//
// goish ships a hand-written backtracking matcher rather than a port of
// Go's NFA, and it had never been diffed against Go. The corpus found
// five classes of silent wrongness, all of which compiled cleanly and
// then answered incorrectly:
//
//   * The matcher worked in BYTES. `.` against "日本語" returned the
//     single byte "\xe6" — not a character, not valid UTF-8, and a
//     third of the rune Go returns. Same for `[^abc]`, `\D`, `\W`,
//     `\S`, and any negated class. A class RANGE was worse:
//     `[あ-ん]` compared UTF-8 bytes against each other, so it matched
//     the middle byte of an unrelated character.
//   * `\b` and `\B` were not implemented and not rejected — `\b`
//     parsed as the literal 'b', so `\bfoo\b` looked for "bfoob".
//   * `[[:alpha:]]` compiled to the class of the letters in "[:alph"
//     and never matched a letter.
//   * `\x41` and `\101` compiled to the literals "x41" and "101".
//   * `a{,3}` failed to compile, where Go treats a `{` that does not
//     open a valid repetition as an ordinary literal.
//
// Fixed here, along with the flags and quantifiers the corpus showed
// were merely absent: `(?s)`, `(?m)`, the non-greedy `*?`/`+?`/`??`,
// named groups, `\A`/`\z`, and the POSIX class names. `(a*)*b` also
// reported its group as "" where Go reports "a" — Go does not keep the
// captures of an empty final iteration.
//
// Still rejected at Compile, and checked as rejections so that a future
// silent acceptance fails this smoke: `\p{...}` and `\pX` (they need
// the Unicode script tables) and lookahead `(?=...)`, which Go rejects
// too.

