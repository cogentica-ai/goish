// Test ECDSA P-256 with a known test vector (NIST FIPS 186-4 / Wycheproof).
#![no_std]
#![no_main]
#![allow(non_snake_case)]
extern crate alloc;
use goish::crypto::ecdsa::{P256PublicKey, VerifyP256};
use goish::syscall;
use goish::fmt;

#[goish::main]
fn main() {
    // NIST P-256 test vector from RFC 6979 §A.2.5:
    //   private key (not needed)
    //   public key Qx, Qy
    //   message "sample"
    //   SHA-256 hash:
    //     af2bdbe1aa9b6ec1e2ade1d694f41fc71a831d0268e9891562113d8a62add1bf
    //   k (deterministic):
    //     a6e3c57dd01abe90086538398355dd4c3b17aa873382b0f24d6129493d8aad60
    //   r = EFD48B2AACB6A8FD1140DD9CD45E81D69D2C877B56AAF991C34D0EA84EAF3716
    //   s = F7CB1C942D657C41D436C7A1B6E29F65F3E900DBB9AFF4064DC4AB2F843ACDA8

    let qx: [u8; 32] = [
        0x60, 0xFE, 0xD4, 0xBA, 0x25, 0x5A, 0x9D, 0x31,
        0xC9, 0x61, 0xEB, 0x74, 0xC6, 0x35, 0x6D, 0x68,
        0xC0, 0x49, 0xB8, 0x92, 0x3B, 0x61, 0xFA, 0x6C,
        0xE6, 0x69, 0x62, 0x2E, 0x60, 0xF2, 0x9F, 0xB6,
    ];
    let qy: [u8; 32] = [
        0x79, 0x03, 0xFE, 0x10, 0x08, 0xB8, 0xBC, 0x99,
        0xA4, 0x1A, 0xE9, 0xE9, 0x56, 0x28, 0xBC, 0x64,
        0xF2, 0xF1, 0xB2, 0x0C, 0x2D, 0x7E, 0x9F, 0x51,
        0x77, 0xA3, 0xC2, 0x94, 0xD4, 0x46, 0x22, 0x99,
    ];

    let digest_sha256: [u8; 32] = [
        0xAF, 0x2B, 0xDB, 0xE1, 0xAA, 0x9B, 0x6E, 0xC1,
        0xE2, 0xAD, 0xE1, 0xD6, 0x94, 0xF4, 0x1F, 0xC7,
        0x1A, 0x83, 0x1D, 0x02, 0x68, 0xE9, 0x89, 0x15,
        0x62, 0x11, 0x3D, 0x8A, 0x62, 0xAD, 0xD1, 0xBF,
    ];

    // DER-encode r, s as SEQUENCE { INTEGER r, INTEGER s }
    let r: [u8; 32] = [
        0xEF, 0xD4, 0x8B, 0x2A, 0xAC, 0xB6, 0xA8, 0xFD,
        0x11, 0x40, 0xDD, 0x9C, 0xD4, 0x5E, 0x81, 0xD6,
        0x9D, 0x2C, 0x87, 0x7B, 0x56, 0xAA, 0xF9, 0x91,
        0xC3, 0x4D, 0x0E, 0xA8, 0x4E, 0xAF, 0x37, 0x16,
    ];
    let s: [u8; 32] = [
        0xF7, 0xCB, 0x1C, 0x94, 0x2D, 0x65, 0x7C, 0x41,
        0xD4, 0x36, 0xC7, 0xA1, 0xB6, 0xE2, 0x9F, 0x65,
        0xF3, 0xE9, 0x00, 0xDB, 0xB9, 0xAF, 0xF4, 0x06,
        0x4D, 0xC4, 0xAB, 0x2F, 0x84, 0x3A, 0xCD, 0xA8,
    ];

    // Build DER signature: 0x30 LEN 0x02 R_LEN R 0x02 S_LEN S
    // Both r and s have high bit set in MSB → prepend 0x00 to indicate positive
    let mut der = alloc::vec::Vec::new();
    der.push(0x30u8);
    let r_high = (r[0] & 0x80) != 0;
    let s_high = (s[0] & 0x80) != 0;
    let r_len = if r_high { 33u8 } else { 32u8 };
    let s_len = if s_high { 33u8 } else { 32u8 };
    der.push(2 + r_len + 2 + s_len); // SEQUENCE length
    der.push(0x02u8); der.push(r_len);
    if r_high { der.push(0x00u8); }
    der.extend_from_slice(&r);
    der.push(0x02u8); der.push(s_len);
    if s_high { der.push(0x00u8); }
    der.extend_from_slice(&s);

    let pk = P256PublicKey { x: qx, y: qy };
    let err = VerifyP256(&pk, &digest_sha256, &der);
    if err.IsNil() {
        fmt::Println!(goish::string("PASS: ECDSA P-256 known-good signature verified"));
        syscall::Exit(0);
    } else {
        fmt::Println!(fmt::Sprintf!("FAIL: ECDSA verify returned err=%v", err));
        syscall::Exit(1);
    }
}
