// strconv_float_ref_smoke — atof.go and ftoa.go against a running Go.
// (strconv/atof.go, strconv/ftoa.go, strconv/decimal.go)
//
// Every expectation below is what a real Go 1.25.5 prints: the vectors
// are the output of `tools/gen_strconv_float_ref.go` run in
// `package strconv_test` by `scripts/goref.sh`.
//
// atof.go and ftoa.go are the two halves of one contract: whatever
// FormatFloat writes with prec -1, ParseFloat must read back to the
// same 64 bits. goish carries the slow multiprecision path only — no
// Eisel-Lemire on the way in, no Ryū on the way out — which is meant to
// be exactly as correct and merely slower. These vectors are where
// "meant to be" gets checked: the subnormal boundary, the largest and
// smallest normals, the powers of ten either side of the exact-float64
// cutoff, halfway cases that decide a rounding direction, and the hex
// forms that skip the decimal machinery entirely.
//
// The three files were also anchored for the first time here. That
// found one behavioural defect on its own: ParseFloat's trailing-junk
// check tested the wrong sentinel. Go returns a SYNTAX error when the
// parse stopped short of the end of the string and the error it has in
// hand is not itself a syntax error; goish tested for a RANGE error, so
// `ParseFloat("1e1000x")` came back "value out of range" — a claim
// about the number — instead of "invalid syntax", a claim about the
// string. Row "1e1000x" in check 3 pins it.

