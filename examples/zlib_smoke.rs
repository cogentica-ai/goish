// zlib_smoke — exercise compress/zlib's RFC 1950 reader + writer.
//
// zlib is a 2-byte header + 4-byte big-endian Adler-32 trailer around
// a raw DEFLATE payload (compress/flate). The strong test is a
// compress -> decompress round-trip entirely through goish.
//
// Coverage:
//   1..5   round-trip at NoCompression / BestSpeed / DefaultCompression
//          / BestCompression / HuffmanOnly, each over 4 inputs
//          (empty, short, highly repetitive, a few KB of mixed data).
//   6      NewWriterLevelDict / NewReaderDict with a preset dictionary.
//   7      Flush mid-stream then continue + Close.
//   8      invalid level rejected by NewWriterLevel.
//   9      corrupted header -> ErrHeader.
//  10      corrupted trailer -> ErrChecksum.
//  11      Go -> goish interop: decompress a real Go-zlib.NewWriter
//          stream (embedded as bytes, generated by the Go toolchain).
//  12      goish -> Go interop: write a goish-compressed stream to a
//          file for the validation step to decompress with Go; also
//          assert the 2-byte header equals Go's for DefaultCompression.

#![no_std]
#![no_main]
#![allow(non_snake_case)]

