// math2_ref_smoke — the math functions goish did not have, vs Go.
// (math/*.go)
//
// Every expectation below is what a real Go 1.25.5 computes: the
// vectors are the output of `tools/gen_math2_ref.go` run in `package
// math_test` by `scripts/goref.sh`, as raw IEEE-754 BIT PATTERNS.
//
// math_ref_smoke diffed the 45 functions goish already had. This one
// covers the twenty it did not: Cbrt, Expm1, Log1p, Erf, Erfc, Gamma,
// Lgamma, Logb, Ilogb, RoundToEven, Sincos, Nextafter, Nextafter32,
// FMA, and the six Bessel functions.
//
// Several exist precisely because the obvious spelling loses precision,
// and their vectors say so:
//
//   * Expm1(1e-10) and Log1p(1e-20) are the values `Exp(x)-1` and
//     `Log(1+x)` cannot produce — the subtraction and the addition each
//     throw away every significant digit.
//   * Erfc is computed directly rather than as 1-Erf(x), which is zero
//     to a float64 well before Erfc is.
//   * FMA rounds ONCE, so it is not `x*y + z` written out.
//
// And two carry sentinels a caller has to know about: Ilogb answers
// MinInt32 for zero and MaxInt32 for NaN and ±Inf, which are not
// errors and read as wildly wrong exponents if ignored.
//
// RoundToEven is the one most likely to surprise: it rounds halves to
// EVEN where Round rounds them away from zero, so Round(2.5) is 3 and
// RoundToEven(2.5) is 2.

