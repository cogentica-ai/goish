fn s(x: &str) -> string {
    return string::from_bytes(x.as_bytes());
}

/// Same bound and reasoning as math_ref_smoke: goish reaches these
/// through libm and Go through its own polynomials, so the last bits
/// can differ.
const ULP_BOUND: int = 8;

fn ulp_diff(a: f64, b: f64) -> int {
    if a.is_nan() || b.is_nan() || a.is_infinite() != b.is_infinite() {
        return -1;
    }
    let (ai, bi) = (a.to_bits() as i64, b.to_bits() as i64);
    if ai > bi {
        return ai - bi;
    }
    return bi - ai;
}

fn near(failed: &mut int, got: f64, want: u64, name: &str, arg: u64) {
    let w = f64::from_bits(want);
    if got.to_bits() == want {
        return;
    }
    if got.is_nan() && w.is_nan() {
        return;
    }
    let u = ulp_diff(got, w);
    if u >= 0 && u <= ULP_BOUND {
        return;
    }
    fmt::Printf!(
        "[!!] %s arg=%d got=%d want=%d ulp=%d\n",
        s(name),
        arg as i64,
        got.to_bits() as i64,
        want as i64,
        u
    );
    *failed += 1;
}

