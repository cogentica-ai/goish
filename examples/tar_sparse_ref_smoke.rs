// tar_sparse_ref_smoke — reading sparse archives in all three
// layouts, against a running Go 1.25.5 via scripts/goref.sh.
//
// A sparse file is stored twice over: the archive holds only the data
// fragments, and a map says where each belongs in the logical file.
// Everything the map does not cover is a hole the reader has to invent
// as zeros. Get that wrong and there is no error to notice — just the
// wrong bytes, of the wrong length.
//
// Which is what this port did. `handleSparseFile` was a stub that
// returned nil, and the waiver above it claimed "a sparse header
// returns ErrHeader rather than being decoded". It did not: it
// returned the DENSE bytes as if they were the file, with err=<nil>.
// On a 4 MiB sparse file from GNU tar 1.35, Go read 4194304 bytes and
// goish read 8192, reporting success.
//
// Three layouts, three code paths, and the map lives somewhere
// different in each:
//
//   old GNU ('S')  inline in the header block at offset 386, four
//                  entries, continuing into extension blocks while
//                  the isExtended byte at 482 is set. The LOGICAL
//                  size is at 483; the size field at 124 holds the
//                  PHYSICAL count. Reading the wrong one of those two
//                  is the whole defect in miniature.
//   PAX 0.0/0.1    entirely in GNU.sparse.* extended-header records,
//                  the pairs comma-separated in GNU.sparse.map.
//   PAX 1.0        a newline-delimited block at the head of the FILE
//                  DATA, ahead of the contents, so reading the map
//                  consumes from the same stream the contents come
//                  from.
//
// In both PAX forms the header's own name is an internal
// `GNUSparseFile.NNN/` placeholder and the real one is in
// GNU.sparse.name — so a reader that ignores the records reports the
// placeholder, which is exactly what goish did.
//
// The archives are hand-built rather than taken from GNU tar, so they
// are small enough to read: one file, logical size 16384, 512 bytes of
// data at offset 4096 and 512 more at 12288. The same bytes were
// handed to Go to produce the expectations below.
