const GO: [&str; 4] = [
    "hdr name=small.dat type=83 size=16384",
    "data len=16384 err=<nil>",
    "runs [4096:4107]\"FIRST-CHUNK\" [12288:12300]\"SECOND-CHUNK\" ",
    "next EOF",
];

fn unhex(parts: &[&str]) -> Vec<u8> {
    let mut out: Vec<u8> = Vec::new();
    for p in parts.iter() {
        let b = p.as_bytes();
        let mut i = 0usize;
        while i + 1 < b.len() {
            let hi = (b[i] as char).to_digit(16).unwrap_or(0) as u8;
            let lo = (b[i + 1] as char).to_digit(16).unwrap_or(0) as u8;
            out.push((hi << 4) | lo);
            i += 2;
        }
    }
    return out;
}

fn chk(ln: &mut usize, got: &string) {
    if *ln >= GO.len() {
        fmt::Printf!("[!!] extra line %d: %q\n", *ln as int + 1, got);
        *ln += 1;
        return;
    }
    if got == GO[*ln] {
        fmt::Printf!("[ok] %s\n", got);
    } else {
        fmt::Printf!("[!!] line %d\n  got  %q\n  want %q\n", *ln as int + 1, got, GO[*ln]);
    }
    *ln += 1;
}

#[goish::main]
fn main() {
    let mut ln: usize = 0;
    let raw = unhex(&ARCHIVE);
    let src = bytes::NewReader(slice::__from_vec(raw));
    let mut tr = tar::NewReader(Box::new(src));

    loop {
        let (hdr, err) = tr.Next();
        if err == io::EOF {
            chk(&mut ln, &fmt::Sprintf!("next EOF"));
            break;
        }
        if !err.IsNil() {
            chk(&mut ln, &fmt::Sprintf!("next ERR %v", err));
            break;
        }
        let (data, rerr) = io::ReadAll(&mut tr);
        chk(&mut ln, &fmt::Sprintf!("hdr name=%s type=%d size=%d",
            hdr.Name, hdr.Typeflag as int, hdr.Size));
        chk(&mut ln, &fmt::Sprintf!("data len=%d err=%v", data.Len() as int, rerr));

        // Where the non-zero bytes are. A reader that ignored the map
        // would put the two chunks at 0 and 512 instead of 4096 and
        // 12288, and this line is what says so.
        let mut runs = string::from("");
        let mut i: usize = 0;
        let n = data.Len() as usize;
        while i < n {
            if data[i] != 0 {
                let mut j = i;
                while j < n && data[j] != 0 {
                    j += 1;
                }
                runs = runs
                    + fmt::Sprintf!("[%d:%d]%q ", i as int, j as int, data.slice(i as int, j as int));
                i = j;
            } else {
                i += 1;
            }
        }
        chk(&mut ln, &fmt::Sprintf!("runs %s", runs));
    }

    if ln != GO.len() {
        fmt::Printf!("[!!] produced %d lines, pinned %d\n", ln as int, GO.len() as int);
    }
}
