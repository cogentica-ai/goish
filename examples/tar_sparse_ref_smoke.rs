// tar_sparse_ref_smoke — reading a GNU sparse archive, against a
// running Go 1.25.5 via scripts/goref.sh.
//
// A sparse file is stored twice over: the archive holds only the data
// fragments, and a map in the header says where each belongs in the
// logical file. Everything the map does not cover is a hole the reader
// has to invent as zeros. Get that wrong and there is no error to
// notice — just the wrong bytes, of the wrong length.
//
// Which is what this port did. `handleSparseFile` was a stub that
// returned nil, and the suppression above it in reader.rs claimed "a
// sparse header returns ErrHeader rather than being decoded". It did
// not: it returned the DENSE bytes as if they were the file, with
// err=<nil>. On a 4 MiB sparse file GNU tar produced here, Go read
// 4194304 bytes and goish read 8192, reporting success.
//
// The archive below is hand-built rather than taken from GNU tar, so
// every field is visible and small: one file, logical size 16384, with
// 512 bytes of data at offset 4096 and 512 more at 12288. The same
// bytes were handed to Go to produce the expectations.
//
// The header is the OLD GNU layout: type flag 'S', magic "ustar  \0",
// the map inline at 386 as four 12-byte octal (offset, length) pairs,
// isExtended at 482, and the LOGICAL size at 483 — while the size
// field at 124 holds the PHYSICAL byte count. Reading the wrong one of
// those two is the whole defect in miniature.
