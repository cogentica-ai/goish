fn line(ln: &mut usize, got: string) {
    unsafe { RUN += 1 };
    if *ln >= GO.len() {
        fmt::Printf!("[!!] extra line %d: %q\n", *ln as int + 1, got);
        unsafe { FAILED += 1 };
        *ln += 1;
        return;
    }
    if got == GO[*ln] {
        fmt::Printf!("[ok] %s\n", got);
    } else {
        fmt::Printf!(
            "[!!] line %d\n  got  %q\n  want %q\n",
            *ln as int + 1,
            got,
            GO[*ln]
        );
        unsafe { FAILED += 1 };
    }
    *ln += 1;
}

/// `%-Ns`, padded by RUNE count as Go's fmt measures it.
fn l(s: string, w: int) -> string {
    let mut o = s;
    while goish::len(&goish::runes(o.clone())) < w {
        o = o + string::from_static(" ");
    }
    return o;
}

/// `%Nd`
fn d(v: i64, w: int) -> string {
    let mut o = strconv::Itoa(int::from(v));
    while o.Len() < w {
        o = string::from_static(" ") + o;
    }
    return o;
}

#[goish::main]
fn main() {
    let mut ln: usize = 0;

    for (i, pat) in PATS.iter().enumerate() {
        let src = string::from_static(pat);
        let head = d(i as i64, int::from(3))
            + string::from_static(" ")
            + l(strconv::Quote(src.clone()), int::from(22))
            + string::from_static(" ");

        let (re, err) = syntax::Parse(src.clone(), syntax::Perl);
        if !err.IsNil() {
            line(
                &mut ln,
                head + string::from_static("parse-error ") + strconv::Quote(err.Error()),
            );
            continue;
        }
        let re = re.MustTake();
        line(
            &mut ln,
            head.clone() + string::from_static("parsed   ") + strconv::Quote(re.String()),
        );

        let sre = re.Simplify();
        line(
            &mut ln,
            head.clone() + string::from_static("simple   ") + strconv::Quote(sre.String()),
        );

        let (prog, cerr) = syntax::Compile(&sre);
        if !cerr.IsNil() {
            line(
                &mut ln,
                head + string::from_static("compile-error ") + strconv::Quote(cerr.Error()),
            );
            continue;
        }
        line(
            &mut ln,
            head.clone()
                + string::from_static("numcap=")
                + strconv::Itoa(prog.NumCap)
                + string::from_static(" start=")
                + strconv::Itoa(prog.Start)
                + string::from_static(" ninst=")
                + strconv::Itoa(int::from(prog.Inst.len() as i64)),
        );
        let (pre, complete) = prog.Prefix();
        line(
            &mut ln,
            head.clone()
                + string::from_static("prefix=")
                + strconv::Quote(pre)
                + string::from_static(" complete=")
                + fmt::Sprintf!("%v", complete)
                + string::from_static(" startcond=")
                + strconv::Itoa(int::from(goish::int64(prog.StartCond().0))),
        );
        line(
            &mut ln,
            head + string::from_static("prog     ") + strconv::Quote(prog.String()),
        );
    }

    let run = unsafe { RUN };
    let f = unsafe { FAILED };
    if run != GO.len() as int {
        fmt::Printf!("\nFAIL ran %d of %d rows\n", run, GO.len() as int);
        goish::os::Exit(1);
    }
    if f == 0 {
        fmt::Printf!("\nok %d/%d\n", run, run);
        goish::os::Exit(0);
    }
    fmt::Printf!("\nFAIL %d\n", f);
    goish::os::Exit(1);
}
