// regexp_compile_ref_smoke — `Simplify` and `Compile`, stage 3 of §2c.
//
// Parse, simplify, compile: the AST becomes a `Prog`. This is the step
// §2c exists for. Once a match is a walk over integer program counters,
// the memo key is `(pc, pos)` — two small integers — and the
// exponential blowup of a backtracker over an AST has nowhere to live.
// The engine that walks it is stage 4.
//
// Each pattern contributes five rows: its parse, its simplification,
// the program's shape (`NumCap`, `Start`, instruction count), the
// prefix and start condition the engine will use to skip work, and the
// full instruction dump.
//
// What the rows are chosen to hold down:
//
//   `(?:a+)+` -> `a+`      simplify1's idempotence, which is why a
//                          nested quantifier does not nest a loop
//   `a{2,5}`  -> `aa(a(a(a)?)?)?`  Go's nesting, "the machine will do
//                          less work if we nest the final m copies"
//   `(?:a*)*`              star of a NULLABLE body compiles as
//                          `(f1+)?`, not as a loop — go.dev/issue/46123
//   `a*?`                  non-greedy puts the body in Arg and leaves
//                          Out as the hole; that swap IS the priority
//                          order
//   `(?i)a` vs `(?i)k`     FoldCase survives only when the rune has a
//                          fold orbit, and `InstRune1` is chosen only
//                          once it is gone
//   `a{0}`                 the empty match, without even considering a
//
// 361 rows from `scripts/goref.sh regexp/syntax
// tools/gen_regexp_compile_ref.go`.

