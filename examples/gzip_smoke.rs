// gzip_smoke — exercise compress/gzip's RFC 1952 reader + writer.
//
// gzip is a variable-length header (magic 1f 8b, method, flags, mtime,
// XFL, OS, optional FEXTRA/FNAME/FCOMMENT/FHCRC fields) + raw DEFLATE
// payload + an 8-byte little-endian CRC-32/IEEE + ISIZE trailer.
//
// Coverage:
//   1..5   round-trip at NoCompression / BestSpeed / DefaultCompression
//          / BestCompression / HuffmanOnly, each over 4 inputs
//          (empty, short, highly repetitive, a few KB of mixed data).
//   6      header fields (Name, Comment, ModTime, Extra) set on the
//          Writer survive a round-trip and read back on the Reader.
//   7      multistream: two gzip members concatenated read as the
//          concatenation of their payloads.
//   8      invalid level rejected by NewWriterLevel.
//   9      corrupt magic -> ErrHeader.
//  10      corrupt trailer CRC -> ErrChecksum.
//  11      Go -> goish interop: decompress a real Go-gzip.NewWriter
//          stream (embedded as bytes, generated by the Go toolchain),
//          checking the Name/Comment header fields too.
//  12      goish -> Go interop: write a goish-compressed stream to a
//          file for the validation step to decompress with Go; also
//          assert the 3-byte magic+method prefix equals Go's.

