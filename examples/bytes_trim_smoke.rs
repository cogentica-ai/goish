// bytes_trim_smoke — bytes' cutset trim family against a running Go.
// (bytes/bytes.go)
//
// Every expectation below is what a real Go 1.25.5 prints: the tables
// are the output of `tools/gen_bytes_trim_ref.go` run in
// `package bytes_test` by `scripts/goref.sh`.
//
// The cutset is a STRING and is decoded as RUNES: `Trim(s, "é")` strips
// the two-byte é, not the bytes 0xC3 and 0xA9 wherever they turn up.
// That is what separates a rune-wise implementation from a byte-wise
// one, and the inputs include a lone 0xC3, a trailing 0xC3 and a pair
// of bare 0xA9s so the two disagree. Go leaves all three untouched
// under cutset "é".
//
// `Trim`, `TrimLeft` and `TrimRight` dispatch three ways on the shape
// of the cutset — one ASCII byte, all ASCII (a 128-bit bitmap), or
// holding a non-ASCII rune — and the twelve cutsets here land in each.

