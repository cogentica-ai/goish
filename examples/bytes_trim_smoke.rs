#[goish::main]
fn main() {
    let mut failed = 0;

    // 1. Trim, TrimLeft and TrimRight over Go's 192 vectors —
    //    twelve cutsets crossed with sixteen inputs, hitting all three
    //    dispatch paths.
    {
        let mut ok = true;
        let mut i = 0;
        while i < TRIM.len() {
            let (c, input, wt, wl, wr) = TRIM[i];
            if raw(&bytes::Trim(sl(input), sl(c))) != wt.to_vec() {
                ok = false;
            }
            if raw(&bytes::TrimLeft(sl(input), sl(c))) != wl.to_vec() {
                ok = false;
            }
            if raw(&bytes::TrimRight(sl(input), sl(c))) != wr.to_vec() {
                ok = false;
            }
            i += 1;
        }
        if ok {
            fmt::Println!("[ 1] Trim/Left/Right x192      PASS");
        } else {
            fmt::Println!("[ 1] Trim/Left/Right x192      FAIL");
            failed += 1;
        }
    }

    // 2. The rune-vs-byte distinction, stated on its own. Under cutset
    //    "é" a byte-wise implementation strips the lone 0xC3 and the
    //    bare 0xA9s; Go strips neither, because neither is the rune é.
    {
        let mut ok = true;
        if raw(&bytes::Trim(sl(b"\xc3abc"), sl("é".as_bytes()))) != b"\xc3abc".to_vec() {
            ok = false;
        }
        if raw(&bytes::Trim(sl(b"abc\xc3"), sl("é".as_bytes()))) != b"abc\xc3".to_vec() {
            ok = false;
        }
        if raw(&bytes::Trim(sl(b"\xa9\xa9"), sl("é".as_bytes()))) != b"\xa9\xa9".to_vec() {
            ok = false;
        }
        // The whole rune, though, does get stripped.
        if raw(&bytes::Trim(sl("éaé".as_bytes()), sl("é".as_bytes()))) != b"a".to_vec() {
            ok = false;
        }
        if raw(&bytes::TrimLeft(sl("éaé".as_bytes()), sl("é".as_bytes())))
            != "aé".as_bytes().to_vec()
        {
            ok = false;
        }
        if ok {
            fmt::Println!("[ 2] cutset is runes, not bytes PASS");
        } else {
            fmt::Println!("[ 2] cutset is runes, not bytes FAIL");
            failed += 1;
        }
    }

    // 3. TrimSpace, which has its own ASCII fast path.
    {
        let mut ok = true;
        let mut i = 0;
        while i < SPACE.len() {
            let (input, want) = SPACE[i];
            if raw(&bytes::TrimSpace(sl(input))) != want.to_vec() {
                ok = false;
            }
            i += 1;
        }
        if ok {
            fmt::Println!("[ 3] TrimSpace                 PASS");
        } else {
            fmt::Println!("[ 3] TrimSpace                 FAIL");
            failed += 1;
        }
    }

    // 4. TrimPrefix and TrimSuffix are whole-affix, not cutset — the
    //    distinction Go's docs point at from TrimLeft/TrimRight.
    {
        let mut ok = true;
        let mut i = 0;
        while i < FIX.len() {
            let (p, input, wp, ws) = FIX[i];
            if raw(&bytes::TrimPrefix(sl(input), sl(p))) != wp.to_vec() {
                ok = false;
            }
            if raw(&bytes::TrimSuffix(sl(input), sl(p))) != ws.to_vec() {
                ok = false;
            }
            i += 1;
        }
        if ok {
            fmt::Println!("[ 4] TrimPrefix/TrimSuffix     PASS");
        } else {
            fmt::Println!("[ 4] TrimPrefix/TrimSuffix     FAIL");
            failed += 1;
        }
    }

    // 5. The three SpecialCase mappings, on the runes Turkish moves.
    {
        let mut ok = true;
        let mut i = 0;
        while i < SPECIAL.len() {
            let (input, wu, wl, wt, pu, pl) = SPECIAL[i];
            if raw(&bytes::ToUpperSpecial(unicode::TurkishCase, sl(input))) != wu.to_vec() {
                ok = false;
            }
            if raw(&bytes::ToLowerSpecial(unicode::TurkishCase, sl(input))) != wl.to_vec() {
                ok = false;
            }
            if raw(&bytes::ToTitleSpecial(unicode::TurkishCase, sl(input))) != wt.to_vec() {
                ok = false;
            }
            if raw(&bytes::ToUpper(sl(input))) != pu.to_vec() {
                ok = false;
            }
            if raw(&bytes::ToLower(sl(input))) != pl.to_vec() {
                ok = false;
            }
            i += 1;
        }
        if ok {
            fmt::Println!("[ 5] To*Special (Turkish)      PASS");
        } else {
            fmt::Println!("[ 5] To*Special (Turkish)      FAIL");
            failed += 1;
        }
    }

    if failed == 0 {
        fmt::Println!("ok 5/5");
        syscall::Exit(0);
    } else {
        fmt::Println!("FAIL", failed, "of 5");
        syscall::Exit(1);
    }
}
