const WANT_APPEND: &str = "<2023-11-14T22:13:20.123456789Z";

#[goish::main]
fn main() {
    let mut failed = 0;

    // 1. Every layout against every instant: 820 renderings.
    {
        let mut ok = true;
        let mut bad = 0;
        let mut li = 0;
        while li < LAYOUTS.len() {
            let mut ti = 0;
            while ti < TIMES.len() {
                let (sec, nsec) = TIMES[ti];
                let got = time::Unix(sec, nsec).Format(LAYOUTS[li]);
                if got != s(WANT[li][ti]) {
                    if bad < 6 {
                        fmt::Println!(
                            "   layout",
                            s(LAYOUTS[li]),
                            "want",
                            s(WANT[li][ti]),
                            "got",
                            got
                        );
                    }
                    bad += 1;
                    ok = false;
                }
                ti += 1;
            }
            li += 1;
        }
        if bad > 0 {
            fmt::Println!("   ", bad, "mismatches");
        }
        report(&mut failed, ok, " 1", "every chunk, every instant");
    }

    // 2. AppendFormat extends dst rather than replacing it.
    {
        let mut v: alloc::vec::Vec<goish::types::byte> = alloc::vec::Vec::new();
        v.push(b'<');
        let dst = goish::goslice::slice::__from_vec(v);
        let got = time::Unix(1_700_000_000, 123_456_789).AppendFormat(dst, time::RFC3339Nano);
        let ok = string::from_bytes(&got.__into_vec()) == s(WANT_APPEND);
        report(&mut failed, ok, " 2", "AppendFormat extends dst");
    }

    // 3. The declared layout constants are the strings Go declares.
    //    They are what a caller passes, and a typo in one of them is
    //    invisible until a round-trip fails.
    {
        let mut ok = true;
        let pairs: [(&str, &str); 19] = [
            (time::Layout, LAYOUTS[0]),
            (time::ANSIC, LAYOUTS[1]),
            (time::UnixDate, LAYOUTS[2]),
            (time::RubyDate, LAYOUTS[3]),
            (time::RFC822, LAYOUTS[4]),
            (time::RFC822Z, LAYOUTS[5]),
            (time::RFC850, LAYOUTS[6]),
            (time::RFC1123, LAYOUTS[7]),
            (time::RFC1123Z, LAYOUTS[8]),
            (time::RFC3339, LAYOUTS[9]),
            (time::RFC3339Nano, LAYOUTS[10]),
            (time::Kitchen, LAYOUTS[11]),
            (time::Stamp, LAYOUTS[12]),
            (time::StampMilli, LAYOUTS[13]),
            (time::StampMicro, LAYOUTS[14]),
            (time::StampNano, LAYOUTS[15]),
            (time::DateTime, LAYOUTS[16]),
            (time::DateOnly, LAYOUTS[17]),
            (time::TimeOnly, LAYOUTS[18]),
        ];
        let mut i = 0;
        while i < pairs.len() {
            let (got, want) = pairs[i];
            if s(got) != s(want) {
                ok = false;
            }
            i += 1;
        }
        report(&mut failed, ok, " 3", "the layout constants themselves");
    }

    if failed == 0 {
        fmt::Println!("ok 3/3");
        syscall::Exit(0);
    } else {
        fmt::Println!("FAIL", failed, "of 3");
        syscall::Exit(1);
    }
}
