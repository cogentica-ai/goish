// time_format_ref_smoke — time.Format against a running Go.
// (time/format.go)
//
// Every expectation below is what a real Go 1.25.5 prints: the vectors
// are the output of `tools/gen_time_format_ref.go` run in
// `package time_test` by `scripts/goref.sh`.
//
// Go's Format is not a table of named layouts. `nextStdChunk` walks any
// layout and hands `appendFormat` one chunk at a time, so a layout
// built by concatenation at run time works exactly as well as a
// constant. goish had a switch over nine named constants in front of a
// hand-rolled scanner that recognised a subset of the chunks: no
// `__2`/`002` day-of-year, no `Z07`/`Z070000`/`Z07:00:00`, no
// `-070000`/`-07:00:00`, no `,000` comma fractions, and its `.999`
// handling was its own.
//
// nextStdChunk is now ported chunk for chunk, and so are appendInt,
// appendNano, stdFracSecond/digitsLen/separator, match and lookup.
// The 82 layouts below cover every chunk in Go's vocabulary plus the
// near-misses the scanner has to REJECT — "Janxx" is a literal, but
// "Jan" followed by an upper-case letter is the month; "_2006" is a
// literal underscore then a long year, not an underscore-day.

