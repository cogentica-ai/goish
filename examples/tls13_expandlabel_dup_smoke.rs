// crypto/tls had TWO HKDF-Expand-Labels, and Go has one.
//
// Go declares `ExpandLabel` once, in crypto/internal/fips140/tls13;
// crypto/tls/key_schedule.go has no such function, it calls
// `tls13.ExpandLabel`. goish declared it twice:
//
//   fips140/tls13/tls13.rs      the anchored port, guard and all
//   crypto/tls/key_schedule.rs  a hand-rolled second copy
//
// Same finding as the duplicate TLS 1.2 PRF, on the 1.3 side, and found
// the same mechanical way (scripts/dup_impl_check.py). This one derives
// every TLS 1.3 traffic key, IV and Finished key.
//
// The two agreed on every input the protocol can produce — but NOT on
// every input. Go refuses `len("tls13 ")+len(label) > 255` and
// `len(context) > 255` with a panic, and explains at length why it
// chose a panic over a randomized return. The hand-rolled copy had no
// such check: it wrote the lengths with `as byte`, so a 250-byte label
// silently wrapped its length prefix and produced an HkdfLabel neither
// side of a handshake would agree on. Unreachable through the protocol
// (labels are fixed constants, context is a transcript hash), which is
// why this is a duplication finding and not a vulnerability — but the
// guard is exactly the kind of thing a second copy loses.
//
// Every expected value came from Go 1.25.5's own tls13.ExpandLabel,
// generated by `scripts/goref.sh crypto/internal/fips140/tls13` and
// committed verbatim as examples/testdata/tls13_expandlabel_ref.txt.
// Both implementations are graded against GO, never against each other.
#![no_std]
#![no_main]
#![allow(non_snake_case)]
extern crate alloc;
extern crate goish;

use alloc::vec::Vec;
use goish::crypto::internal::fips140::tls13;
use goish::crypto::sha256;
use goish::crypto::sha512;
use goish::crypto::tls::key_schedule;
use goish::fmt;
use goish::goslice::slice;
use goish::gostring::string;
use goish::hash::Hash as HashTrait;
use goish::types::{byte, int};

const REF: &str = include_str!("testdata/tls13_expandlabel_ref.txt");

fn mk(n: int, off: int) -> Vec<byte> {
    let mut b: Vec<byte> = Vec::new();
    let mut i: int = 0;
    while i < n {
        b.push(((i * 7 + off * 31) & 0xff) as byte);
        i += 1;
    }
    return b;
}

fn label_of(li: int) -> &'static str {
    let labels: [&'static str; 9] = [
        "key",
        "iv",
        "finished",
        "traffic upd",
        "derived",
        "c hs traffic",
        "res binder",
        "",
        "x",
    ];
    return labels[li as usize];
}

fn hex_of(b: &[byte]) -> string {
    let mut s = string::from_static("");
    for &x in b.iter() {
        s = s + fmt::Sprintf!("%02x", goish::int(x));
    }
    return s;
}

static mut PASS: int = 0;
static mut FAIL: int = 0;
static mut ROWS: int = 0;

fn check(what: string, got: string, want: &str) {
    unsafe {
        if got == string::from_bytes(want.as_bytes()) {
            PASS += 1;
        } else {
            FAIL += 1;
            fmt::Printf!("FAIL %s: got %s want %s\n", what, got.clone(), want);
        }
    }
}

type HashFn = fn() -> alloc::boxed::Box<dyn HashTrait + Send + Sync>;

#[goish::main]
fn main() {
    for line in REF.split('\n') {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        let mut it = line.split(' ');
        let hb: int = it.next().unwrap_or("").parse::<i64>().unwrap_or(-1);
        let li: int = it.next().unwrap_or("").parse::<i64>().unwrap_or(-1);
        let sl: int = it.next().unwrap_or("").parse::<i64>().unwrap_or(-1);
        let cl: int = it.next().unwrap_or("").parse::<i64>().unwrap_or(-1);
        let kl: int = it.next().unwrap_or("").parse::<i64>().unwrap_or(-1);
        let want: &str = it.next().unwrap_or("");
        if hb < 0 || li < 0 || sl < 0 || cl < 0 || kl < 0 {
            fmt::Printf!("FAIL unparsable reference row\n");
            unsafe {
                FAIL += 1;
            }
            continue;
        }
        unsafe {
            ROWS += 1;
        }

        let hash_fn: HashFn = if hb == 256 {
            sha256::NewHash as HashFn
        } else {
            sha512::NewHash384 as HashFn
        };
        let secret = mk(sl, li);
        let context = mk(cl, li + 1);
        let label = label_of(li);
        let tag = fmt::Sprintf!("sha%v li=%v sl=%v cl=%v kl=%v", hb, li, sl, cl, kl);

        // The anchored port.
        let ported = tls13::ExpandLabel(
            hash_fn,
            slice::<byte>::__from_vec(secret.clone()),
            label,
            slice::<byte>::__from_vec(context.clone()),
            kl,
        );
        let pb: &[byte] = &ported;
        check(tag.clone() + string::from_static(" ported"), hex_of(pb), want);

        // The copy in key_schedule.rs.
        let ks = key_schedule::ExpandLabel(hash_fn, &secret, label, &context, kl as usize);
        check(
            tag + string::from_static(" key_schedule"),
            hex_of(&ks),
            want,
        );
    }

    unsafe {
        let rows = ROWS;
        if rows < 600 {
            fmt::Printf!("FAIL only %v reference rows ran; expected >= 600\n", rows);
            FAIL += 1;
        }
        let (pass, fail) = (PASS, FAIL);
        fmt::Printf!(
            "tls13_expandlabel_dup_smoke: %v rows, %v checks, %v failed\n",
            rows,
            pass + fail,
            fail
        );
        if fail > 0 {
            goish::syscall::Exit(1);
        }
    }
}
